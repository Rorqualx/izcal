//! Emitting `hg-fontfmt` from a checked model.
//!
//! Four outputs, as fonts and text 6.2 lists them: the zero-copy reader,
//! a Kani harness per accessor (TX-11), a structure-aware fuzz grammar,
//! and the anchor index.
//!
//! The reader has one rule, and the generator is the only thing that has
//! to keep it: **every access is bounds-checked, always**. Memory safety
//! never depends on validation (6.2), so an accessor returns `Option`
//! and never panics — no indexing, no `unwrap`, no `as`, and every
//! offset and count computed with checked arithmetic widened to `i64`
//! before it is narrowed to a `usize`.

use std::fmt::Write as _;

use crate::check::Model;
use crate::syntax::{Expr, Field, Record, Scalar, Table, Term, Ty};

/// How many bytes a Kani harness gives a table. Small on purpose: the
/// proofs are about the arithmetic, which does not care how long the
/// slice is, and a larger bound costs solver time without covering a
/// case the smaller one misses.
pub const PROOF_BOUND: usize = 24;

fn header(what: &str) -> String {
    format!(
        "// @generated by hg-fontgen from the .hgfont descriptions in \
         crates/hg-fontfmt/tables.\n// Do not edit: change the descriptions and run \
         `cargo run -p hg-fontgen -- generate`.\n// {what}\n\n"
    )
}

/// The reader: every record and table.
#[must_use]
pub fn tables(m: &Model) -> String {
    let mut out = header("The reader. Every accessor is total: it returns None rather than panic.");
    out.push_str(
        "//! Readers for the described tables.\n\
         //!\n\
         //! Each table wraps its own bytes and reads nothing until an\n\
         //! accessor is called. An accessor checks its bounds every time,\n\
         //! so a corrupt or hostile font yields `None` and never a panic\n\
         //! (fonts and text 6.2, TX-11).\n\n\
         use crate::read;\n\n",
    );

    for (name, (r, size)) in &m.records {
        emit_record(&mut out, name, r, *size, m);
    }
    for t in &m.tables {
        emit_table(&mut out, t, m);
    }
    out
}

fn doc(out: &mut String, indent: &str, text: &str, anchor: &str) {
    let _ = writeln!(out, "{indent}/// {text}");
    let _ = writeln!(out, "{indent}///");
    let _ = writeln!(out, "{indent}/// Specified at `{anchor}`.");
}

fn emit_record(out: &mut String, name: &str, r: &Record, size: usize, m: &Model) {
    doc(out, "", &format!("The `{name}` record."), &r.anchor);
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    let _ = writeln!(out, "pub struct {name} {{");
    for f in &r.fields {
        doc(out, "    ", &format!("`{}`.", f.name), &f.anchor);
        let _ = writeln!(out, "    pub {}: {},", f.name, field_rust(&f.ty));
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "impl {name} {{");
    let _ = writeln!(
        out,
        "    /// Its size in bytes, which is a constant: a record holds\n\
         \x20   /// no arrays, so an array of records can be indexed.\n\
         \x20   pub const SIZE: usize = {size};\n"
    );
    out.push_str(
        "    /// Reads one at `off`, or `None` when the bytes are not\n\
         \x20   /// there.\n\
         \x20   #[must_use]\n\
         \x20   pub fn read(data: &[u8], off: usize) -> Option<Self> {\n\
         \x20       Some(Self {\n",
    );
    let mut at = 0_usize;
    for f in &r.fields {
        let _ = writeln!(
            out,
            "            {}: {},",
            f.name,
            read_call(&f.ty, &format!("off.checked_add({at})?"))
        );
        at = at.saturating_add(m.elem_size(&f.ty, "", f.line).unwrap_or(0));
    }
    out.push_str("        })\n    }\n}\n\n");
}

fn field_rust(ty: &Ty) -> String {
    match ty {
        Ty::Scalar(s) => s.rust().to_owned(),
        Ty::Record(n) => n.clone(),
        Ty::Array { elem, .. } => field_rust(elem),
    }
}

fn read_call(ty: &Ty, off: &str) -> String {
    match ty {
        Ty::Scalar(s) => format!("read::{}(data, {off})?", s.reader()),
        Ty::Record(n) => format!("{n}::read(data, {off})?"),
        Ty::Array { elem, .. } => read_call(elem, off),
    }
}

fn emit_table(out: &mut String, t: &Table, m: &Model) {
    let name = &t.name;
    doc(out, "", &format!("The `{name}` table."), &t.anchor);
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    let _ = writeln!(out, "pub struct {name}<'a> {{");
    out.push_str("    data: &'a [u8],\n");
    for (p, s) in &t.params {
        let _ = writeln!(out, "    {p}: {},", s.rust());
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "impl<'a> {name}<'a> {{");
    let args: String = t
        .params
        .iter()
        .map(|(p, s)| format!(", {p}: {}", s.rust()))
        .collect();
    let inits: String = t
        .params
        .iter()
        .map(|(p, _)| format!("            {p},\n"))
        .collect();
    let _ = writeln!(
        out,
        "    /// Wraps the table's bytes. Nothing is read here: every\n\
         \x20   /// accessor checks its own bounds.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn new(data: &'a [u8]{args}) -> Self {{\n\
         \x20       Self {{\n            data,\n{inits}        }}\n    }}\n\n\
         \x20   /// The bytes it was given.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn data(&self) -> &'a [u8] {{\n        self.data\n    }}\n"
    );

    // Offsets, in declaration order. `fixed` accumulates while every
    // preceding field has a constant size; after the first array it is
    // the start of a computed chain.
    let mut fixed = 0_usize;
    let mut computed: Vec<String> = Vec::new();
    for f in &t.fields {
        emit_offset(out, f, fixed, &computed);
        match &f.ty {
            Ty::Scalar(s) => fixed = fixed.saturating_add(s.width()),
            Ty::Record(n) => {
                fixed = fixed.saturating_add(m.records.get(n).map_or(0, |(_, s)| *s));
            }
            Ty::Array { elem, .. } => {
                let unit = match &**elem {
                    Ty::Record(n) => format!("{n}::SIZE"),
                    _ => m.elem_size(elem, "", 0).unwrap_or(0).to_string(),
                };
                computed.push(format!(
                    "self.{}_len()?.checked_mul({unit})?",
                    f.name.clone()
                ));
            }
        }
        emit_accessor(out, f, t, m);
    }
    out.push_str("}\n\n");
}

fn emit_offset(out: &mut String, f: &Field, fixed: usize, computed: &[String]) {
    let _ = writeln!(
        out,
        "\n    /// The offset of `{}` from the start of the table.",
        f.name
    );
    let _ = writeln!(out, "    fn off_{}(&self) -> Option<usize> {{", f.name);
    if computed.is_empty() {
        let _ = writeln!(out, "        Some({fixed})");
    } else {
        let _ = writeln!(out, "        let mut off: usize = {fixed};");
        for c in computed {
            let _ = writeln!(out, "        off = off.checked_add({c})?;");
        }
        out.push_str("        Some(off)\n");
    }
    out.push_str("    }\n");
}

fn emit_accessor(out: &mut String, f: &Field, t: &Table, m: &Model) {
    match &f.ty {
        Ty::Scalar(s) => {
            doc(out, "    ", &format!("`{}`.", f.name), &f.anchor);
            let _ = writeln!(
                out,
                "    #[must_use]\n    pub fn {}(&self) -> Option<{}> {{\n        \
                 read::{}(self.data, self.off_{}()?)\n    }}",
                f.name,
                s.rust(),
                s.reader(),
                f.name
            );
        }
        Ty::Record(n) => {
            doc(out, "    ", &format!("`{}`.", f.name), &f.anchor);
            let _ = writeln!(
                out,
                "    #[must_use]\n    pub fn {}(&self) -> Option<{n}> {{\n        \
                 {n}::read(self.data, self.off_{}()?)\n    }}",
                f.name, f.name
            );
        }
        Ty::Array { count, elem } => {
            let rust = field_rust(elem);
            let unit = match &**elem {
                Ty::Record(n) => format!("{n}::SIZE"),
                _ => m.elem_size(elem, "", 0).unwrap_or(0).to_string(),
            };
            let _ = writeln!(
                out,
                "\n    /// How many `{}` the table declares. A declared\n\
                 \x20   /// count is not a promise that the bytes are there:\n\
                 \x20   /// the element accessor checks that too.",
                f.name
            );
            let _ = writeln!(
                out,
                "    #[must_use]\n    pub fn {}_len(&self) -> Option<usize> {{",
                f.name
            );
            out.push_str("        let mut acc: i64 = 0;\n");
            emit_expr(out, count, t);
            out.push_str("        usize::try_from(acc.max(0)).ok()\n    }\n");

            doc(
                out,
                "    ",
                &format!("One `{}`, or `None` when it is not there.", f.name),
                &f.anchor,
            );
            let _ = writeln!(
                out,
                "    #[must_use]\n    pub fn {}(&self, index: usize) -> Option<{rust}> {{\n\
                 \x20       if index >= self.{}_len()? {{\n            return None;\n        }}\n\
                 \x20       let off = self\n            .off_{}()?\n            \
                 .checked_add(index.checked_mul({unit})?)?;\n        {}\n    }}",
                f.name,
                f.name,
                f.name,
                read_elem(elem, "self.data", "off")
            );
        }
    }
}

fn read_elem(elem: &Ty, data: &str, off: &str) -> String {
    match elem {
        Ty::Scalar(s) => format!("read::{}({data}, {off})", s.reader()),
        Ty::Record(n) => format!("{n}::read({data}, {off})"),
        Ty::Array { .. } => "None".to_owned(),
    }
}

/// A count expression, accumulated in `i64` so a difference may go
/// negative without wrapping; the caller clamps at zero.
fn emit_expr(out: &mut String, e: &Expr, t: &Table) {
    for (plus, term) in &e.terms {
        let op = if *plus { "checked_add" } else { "checked_sub" };
        let value = match term {
            Term::Int(n) => format!("i64::from({n}_u32)"),
            Term::Name(n) => {
                if t.params.iter().any(|(p, _)| p == n) {
                    format!("i64::from(self.{n})")
                } else {
                    format!("i64::from(self.{n}()?)")
                }
            }
        };
        let _ = writeln!(out, "        acc = acc.{op}({value})?;");
    }
    if let Some(d) = e.divisor {
        let _ = writeln!(out, "        acc = acc.checked_div(i64::from({d}_u32))?;");
    }
}

/// A Kani harness per accessor (TX-11): for arbitrary bytes, arbitrary
/// parameters and an arbitrary index, calling the accessor must not
/// panic, overflow or read outside the slice.
#[must_use]
pub fn proofs(m: &Model) -> String {
    let mut out = header("The proofs. One harness per accessor (TX-11).");
    out.push_str(
        "//! Kani harnesses: every accessor is total.\n\
         //!\n\
         //! Kani proves the absence of panics, arithmetic overflow and\n\
         //! out-of-bounds access for every input the harness admits. Each\n\
         //! harness gives the table arbitrary bytes, arbitrary parameters\n\
         //! and an arbitrary index, so what is proved is that *no* font\n\
         //! can make the accessor do anything but answer or decline.\n\n\
         #![cfg(kani)]\n\n\
         use crate::tables::*;\n\n",
    );
    let _ = writeln!(
        out,
        "/// How many bytes each harness gives a table.\nconst BOUND: usize = {PROOF_BOUND};\n"
    );

    for (name, (r, _)) in &m.records {
        let _ = writeln!(
            out,
            "/// `{name}::read` is total.\n#[kani::proof]\nfn {}_read_is_total() {{\n    \
             let data: [u8; BOUND] = kani::any();\n    let off: usize = kani::any();\n    \
             let _ = {name}::read(&data, off);\n}}\n",
            snake(name)
        );
        let _ = r;
    }
    for t in &m.tables {
        let params: String = t
            .params
            .iter()
            .map(|(p, s)| format!("    let {p}: {} = kani::any();\n", s.rust()))
            .collect();
        let args: String = t
            .params
            .iter()
            .map(|(p, _)| format!(", {p}"))
            .collect::<String>();
        for f in &t.fields {
            let (extra, call) = match &f.ty {
                Ty::Array { .. } => (
                    "    let index: usize = kani::any();\n".to_owned(),
                    format!(
                        "let _ = table.{}(index);\n    let _ = table.{}_len();",
                        f.name, f.name
                    ),
                ),
                _ => (String::new(), format!("let _ = table.{}();", f.name)),
            };
            let _ = writeln!(
                out,
                "/// `{}::{}` is total.\n#[kani::proof]\nfn {}_{}_is_total() {{\n    \
                 let data: [u8; BOUND] = kani::any();\n{params}{extra}    \
                 let table = {}::new(&data{args});\n    {call}\n}}\n",
                t.name,
                f.name,
                snake(&t.name),
                f.name,
                t.name
            );
        }
    }
    out
}

/// `UpperCamelCase` to `snake_case`, for harness names.
fn snake(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.char_indices() {
        if c.is_ascii_uppercase() {
            if i != 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// The structure-aware fuzz grammar: one row per field, giving a fuzzer
/// enough to build a partially valid table. Random mutation "rarely
/// produce[s] partially valid structures", which is why this exists
/// rather than a plain byte fuzzer (fonts and text 6.2).
#[must_use]
pub fn grammar(m: &Model) -> String {
    let mut out = String::from(
        "# @generated by hg-fontgen. The structure-aware fuzz grammar.\n\
         # kind\towner\tfield\tshape\tdetail\tanchor\n",
    );
    for (name, (r, size)) in &m.records {
        let _ = writeln!(out, "record\t{name}\t\tsize\t{size}\t{}", r.anchor);
        for f in &r.fields {
            let _ = writeln!(
                out,
                "field\t{name}\t{}\t{}\t{}\t{}",
                f.name,
                shape(&f.ty),
                detail(&f.ty, m),
                f.anchor
            );
        }
    }
    for t in &m.tables {
        let params: Vec<String> = t
            .params
            .iter()
            .map(|(p, s)| format!("{p}:{}", s.rust()))
            .collect();
        let _ = writeln!(
            out,
            "table\t{}\t\tparams\t{}\t{}",
            t.name,
            params.join(","),
            t.anchor
        );
        for f in &t.fields {
            let _ = writeln!(
                out,
                "field\t{}\t{}\t{}\t{}\t{}",
                t.name,
                f.name,
                shape(&f.ty),
                detail(&f.ty, m),
                f.anchor
            );
        }
    }
    out
}

fn shape(ty: &Ty) -> &'static str {
    match ty {
        Ty::Scalar(_) => "scalar",
        Ty::Record(_) => "record",
        Ty::Array { .. } => "array",
    }
}

fn detail(ty: &Ty, m: &Model) -> String {
    match ty {
        Ty::Scalar(s) => format!("{}:{}", s.rust(), s.width()),
        Ty::Record(n) => format!("{n}:{}", m.records.get(n).map_or(0, |(_, s)| *s)),
        Ty::Array { count, elem } => {
            let terms: Vec<String> = count
                .terms
                .iter()
                .map(|(plus, t)| {
                    let sign = if *plus { "+" } else { "-" };
                    match t {
                        Term::Int(n) => format!("{sign}{n}"),
                        Term::Name(n) => format!("{sign}{n}"),
                    }
                })
                .collect();
            let div = count.divisor.map_or_else(String::new, |d| format!("/{d}"));
            format!("{}*[{}{div}]", detail(elem, m), terms.join(""))
        }
    }
}

/// The anchor index: every specification clause the descriptions name.
#[must_use]
pub fn anchors(m: &Model) -> String {
    let mut out = String::from("# @generated by hg-fontgen. Anchors, one per line.\n");
    for a in &m.anchors {
        let _ = writeln!(out, "{a}");
    }
    out
}

