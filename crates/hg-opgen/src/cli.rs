//! The generator's file handling: which sources it reads, which outputs it
//! writes, the freshness check (OC-16, G16) and anchor pinning (OC-12).

use std::collections::BTreeMap;
use std::path::Path;

use crate::anchors::{self, IdSource, Pins};
use crate::diag::Diags;
use crate::model::Model;

/// The directory of `.hgop` sources, relative to the workspace root.
pub const SOURCES: &str = "crates/hg-js-ops/ops";

/// Reads every `.hgop` file in [`SOURCES`], sorted by name (the opcode
/// order is the declaration order across the sorted files).
///
/// # Errors
/// An I/O failure, as text.
pub fn read_sources(root: &Path) -> Result<Vec<(String, String)>, String> {
    let dir = root.join(SOURCES);
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(Result::ok)
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| n.ends_with(".hgop"))
        .collect();
    names.sort();
    let mut out = Vec::new();
    for n in names {
        let text = std::fs::read_to_string(dir.join(&n)).map_err(|e| format!("{n}: {e}"))?;
        // Line endings are normalized, so a checkout with CRLF endings
        // generates the same bytes (OC-15).
        out.push((format!("{SOURCES}/{n}"), text.replace("\r\n", "\n")));
    }
    Ok(out)
}

/// The pinned anchor ids: from `$IZCAL_TEST_DATA`'s pinned `spec.html`
/// where it has one, else from the checked-in pin list.
///
/// # Errors
/// An unreadable pin list.
pub fn pins(root: &Path) -> Result<Pins, String> {
    let path = root.join(anchors::PIN_FILE);
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let mut p = anchors::parse_pins(&text);
    if let Ok(dir) = std::env::var("IZCAL_TEST_DATA") {
        let dir = Path::new(&dir);
        let mut entries: Vec<_> = std::fs::read_dir(dir)
            .map(|rd| rd.filter_map(Result::ok).collect())
            .unwrap_or_default();
        entries.sort_by_key(std::fs::DirEntry::file_name);
        for e in entries {
            let name = e.file_name().to_string_lossy().to_string();
            let Some(spec) = anchors::spec_of_dir(&name) else {
                continue;
            };
            let html = e.path().join("spec.html");
            let Ok(text) = std::fs::read_to_string(&html) else {
                continue;
            };
            let label = format!("$IZCAL_TEST_DATA/{name}/spec.html");
            p.ids
                .insert(spec.name().to_string(), anchors::html_ids(&text));
            p.revision
                .insert(spec.name().to_string(), format!("test-data {name}"));
            p.source
                .insert(spec.name().to_string(), IdSource::TestData(label));
        }
    }
    Ok(p)
}

fn render(d: &Diags, names: &[String]) -> String {
    d.0.iter()
        .map(|x| x.render(names))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The CS-ST-17 header naming the generator and its inputs.
pub fn header(names: &[String]) -> String {
    let files: Vec<&str> = names
        .iter()
        .map(|n| n.rsplit('/').next().unwrap_or(n))
        .collect();
    format!(
        "// @generated by hg-opgen from {SOURCES}/{{{}}}.\n// Do not edit: change the .hgop files and run `cargo run -p hg-opgen -- generate`\n// (coding standard CS-ST-17; JS spec G16).\n",
        files.join(",")
    )
}

/// Generated files: path relative to the root, and contents.
pub type Outputs = Vec<(String, String)>;

/// Every output: path relative to the root, and its contents.
///
/// The Rust outputs are formatted by the pinned toolchain's rustfmt (as
/// `hg-ipc-codegen` does), so the checked-in files pass the rustfmt check
/// and are the same on every OS (OC-15).
///
/// # Errors
/// rustfmt could not run or rejected an output.
pub fn outputs(
    model: &Model,
    flows: &crate::flow::Flows,
    pins: &Pins,
    names: &[String],
) -> Result<Outputs, String> {
    let h = header(names);
    let raw: Outputs = vec![
        (
            "crates/hg-js-bytecode/src/generated/opcodes.rs".into(),
            crate::emit_tables::emit_opcodes(model, flows, &h),
        ),
        (
            "crates/hg-js-ops/src/generated/defs.rs".into(),
            crate::emit_interp::emit_consts(model, &h),
        ),
        (
            "crates/hg-js-ops/src/generated/interp.rs".into(),
            crate::emit_interp::emit(model, flows, &h),
        ),
        (
            "crates/hg-js-ops/src/generated/facts.rs".into(),
            crate::emit_tables::emit_facts_rs(model, flows, &h),
        ),
        (
            "crates/hg-js-ops/src/generated/facts.tsv".into(),
            crate::emit_tables::emit_facts_tsv(model, flows, &h),
        ),
        (
            "crates/hg-js-ops/src/generated/anchors.tsv".into(),
            crate::emit_tables::emit_anchors_tsv(model, pins, &h),
        ),
    ];
    raw.into_iter()
        .map(|(path, text)| {
            if path.ends_with(".rs") {
                let t = rustfmt(&text).map_err(|e| format!("{path}: rustfmt: {e}"))?;
                Ok((path, t))
            } else {
                Ok((path, text))
            }
        })
        .collect()
}

/// `text` formatted by rustfmt (edition 2024, Unix line endings).
fn rustfmt(text: &str) -> Result<String, String> {
    use std::io::Write as _;
    use std::process::{Command, Stdio};
    let mut child = Command::new("rustfmt")
        .args([
            "--edition",
            "2024",
            "--emit",
            "stdout",
            "--config",
            "newline_style=Unix",
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| e.to_string())?;
    let mut stdin = child.stdin.take().ok_or("no stdin")?;
    let input = text.to_string();
    // Written from a thread so a large output cannot fill the pipe first.
    let writer = std::thread::spawn(move || stdin.write_all(input.as_bytes()));
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    writer
        .join()
        .map_err(|_| "the writer panicked".to_string())?
        .map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into_owned());
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

/// Loads, checks (OC-1 to OC-17) and generates: the outputs, the notes
/// (declarations wider than their inference, which OC-5 reports without
/// failing), and where the anchors were checked.
///
/// # Errors
/// The rejections, as text.
pub fn build(root: &Path) -> Result<(Outputs, Vec<String>), String> {
    let sources = read_sources(root)?;
    let names: Vec<String> = sources.iter().map(|s| s.0.clone()).collect();
    let (model, flows) = crate::load(&sources).map_err(|d| render(&d, &names))?;
    let pins = pins(root)?;
    let mut diags = Diags::default();
    anchors::check(&model, &pins, &mut diags);
    if !diags.is_empty() {
        return Err(render(&diags.sorted(), &names));
    }
    let mut notes = crate::notes(&model, &flows);
    for (spec, src) in &pins.source {
        notes.push(match src {
            IdSource::TestData(p) => format!("note: OC-12: {spec} anchors checked against {p}"),
            IdSource::PinList => format!(
                "note: OC-12: {spec} anchors checked against the checked-in pin list {} ($IZCAL_TEST_DATA has no pinned spec.html for it)",
                anchors::PIN_FILE
            ),
        });
    }
    Ok((outputs(&model, &flows, &pins, &names)?, notes))
}

/// Runs `generate`, `check`, `pin` or `dump` over the workspace at `root`.
///
/// # Errors
/// The rejections, the stale outputs or an I/O failure, as text.
pub fn run(root: &Path, args: &[String]) -> Result<(), String> {
    let mode = args.first().map_or("check", String::as_str);
    match mode {
        "generate" | "check" => {
            let (outs, notes) = build(root)?;
            for n in &notes {
                eprintln!("{n}");
            }
            let mut stale = Vec::new();
            for (path, text) in outs {
                let full = root.join(&path);
                let current = std::fs::read_to_string(&full).unwrap_or_default();
                if current == text {
                    continue;
                }
                if mode == "check" {
                    stale.push(path);
                } else {
                    if let Some(dir) = full.parent() {
                        std::fs::create_dir_all(dir)
                            .map_err(|e| format!("{}: {e}", dir.display()))?;
                    }
                    std::fs::write(&full, text).map_err(|e| format!("{path}: {e}"))?;
                    println!("wrote {path}");
                }
            }
            if stale.is_empty() {
                Ok(())
            } else {
                Err(format!(
                    "OC-16: stale generated files (run `cargo run -p hg-opgen -- generate`):\n  {}",
                    stale.join("\n  ")
                ))
            }
        }
        "pin" => pin(root, &args[1..]),
        other => Err(format!(
            "usage: hg-opgen generate | check | pin <spec>=<spec.html>=<revision>...\nunknown mode `{other}`"
        )),
    }
}

/// `hg-opgen pin ecma262=<path>=<revision> temporal=<path>=<revision>`:
/// writes the pin list from rendered specifications.
fn pin(root: &Path, args: &[String]) -> Result<(), String> {
    let mut specs: BTreeMap<String, (String, String)> = BTreeMap::new();
    for a in args {
        let mut parts = a.splitn(3, '=');
        let (Some(spec), Some(path), Some(rev)) = (parts.next(), parts.next(), parts.next()) else {
            return Err(format!(
                "`{a}`: expected <spec>=<path to spec.html>=<revision text>"
            ));
        };
        let html = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
        specs.insert(spec.to_string(), (rev.to_string(), html));
    }
    let sources = read_sources(root)?;
    let names: Vec<String> = sources.iter().map(|s| s.0.clone()).collect();
    let (model, _) = crate::load(&sources).map_err(|d| render(&d, &names))?;
    let text = anchors::pin_text(&model, &specs).map_err(|missing| {
        format!(
            "OC-12: these ids are not in the given specifications:\n  {}",
            missing.join("\n  ")
        )
    })?;
    let path = root.join(anchors::PIN_FILE);
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("wrote {}", anchors::PIN_FILE);
    Ok(())
}
