//! Writing `hg-css-props` from the checked overlay.
//!
//! Four outputs, and the split between them is about what every
//! renderer pays for:
//!
//! - `generated/kinds.rs` — the closed set of computed-value kinds.
//! - `generated/properties.rs` — the table proper: one row per
//!   property, a constant per property, and the name index that
//!   `hg-css-syntax` consults to tell a declaration from a rule.
//! - `generated/grammars.rs` — the value grammars and the defining
//!   URLs, behind the `reference` feature. They are large, and only
//!   `hg-style-reference` and DevTools read them; a site process should
//!   not carry a quarter of a megabyte of specification prose it never
//!   looks at.
//! - `generated/properties.tsv` — every column in one table, not
//!   compiled. This is what a re-pin is triaged against.
//!
//! Everything is sorted by property name, so the output depends on the
//! overlay and not on the order its files were read.

use std::fmt::Write as _;

use crate::check::Model;
use crate::syntax::{Affect, PropertyDecl};

/// The header every generated file carries.
fn header(out: &mut String, what: &str, sources: &str) {
    let _ = writeln!(
        out,
        "// @generated by hg-cssgen from {sources}. Do not edit.\n\
         //\n\
         // {what}\n\
         //\n\
         // Run `cargo run -p hg-cssgen -- generate` after changing the\n\
         // overlay; `tools/checks.sh` fails when this file is stale (G29).\n"
    );
}

/// The Rust constant name for a property: `-webkit-text-stroke` becomes
/// `WEBKIT_TEXT_STROKE`.
#[must_use]
pub fn constant(name: &str) -> String {
    name.trim_start_matches('-')
        .replace('-', "_")
        .to_ascii_uppercase()
}

/// The Rust variant name for a kind: `absolute-length` becomes
/// `AbsoluteLength`.
#[must_use]
pub fn variant(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('-') {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            out.push_str(cs.as_str());
        }
    }
    out
}

fn string(s: &str) -> String {
    format!("{s:?}")
}

fn opt_string(s: Option<&String>) -> String {
    s.map_or_else(|| "None".to_owned(), |v| format!("Some({})", string(v)))
}

/// `generated/kinds.rs`.
#[must_use]
pub fn kinds(m: &Model) -> String {
    let mut out = String::new();
    header(
        &mut out,
        "The closed set of computed-value kinds (style spec 6.6, ST-D6).",
        "the .hgprop overlay",
    );
    out.push_str(
        "/// Which conversion a property's computed value needs.\n\
         ///\n\
         /// Not its *type*, which is per-property: this says which of\n\
         /// the conversions in CSS Cascade applies, so the specified\n\
         /// value can be taken to a computed one. Every distinct\n\
         /// computed-value text `@webref/css` carries is classified\n\
         /// into exactly one of these, by hand, in the overlay.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum ComputedKind {\n",
    );
    for k in &m.kinds {
        let _ = writeln!(out, "    /// {}\n    {},", k.doc, variant(&k.name));
    }
    out.push_str("}\n\nimpl ComputedKind {\n");
    out.push_str(
        "    /// Its name in the overlay, which is also what the review\n\
         \x20   /// table and DevTools show.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn name(self) -> &'static str {\n\
         \x20       match self {\n",
    );
    for k in &m.kinds {
        let _ = writeln!(
            out,
            "            Self::{} => {},",
            variant(&k.name),
            string(&k.name)
        );
    }
    out.push_str("        }\n    }\n\n");
    let _ = writeln!(
        out,
        "    /// Every kind, in the order the overlay declares them.\n    \
         pub const ALL: [Self; {}] = [",
        m.kinds.len()
    );
    for k in &m.kinds {
        let _ = writeln!(out, "        Self::{},", variant(&k.name));
    }
    out.push_str("    ];\n}\n");
    out
}

/// `generated/properties.rs`.
#[must_use]
pub fn properties(m: &Model) -> String {
    let mut out = String::new();
    header(
        &mut out,
        "The property table: every property @webref/css carries at the \
         pinned version, with the overlay's columns.",
        "the .hgprop overlay and @webref/css",
    );
    out.push_str(
        "use crate::generated::kinds::ComputedKind;\n\
         use crate::table::{Affects, Property, Row};\n\n",
    );

    let mut index: std::collections::BTreeMap<&str, usize> = m
        .properties
        .iter()
        .enumerate()
        .map(|(i, p)| (p.name.as_str(), i))
        .collect();
    // An alias resolves to its property, so a longhand list that names
    // one — `font` names `font-stretch` — lands on what is stored.
    for a in &m.aliases {
        if let Some(i) = index.get(a.target.as_str()).copied() {
            index.insert(a.name.as_str(), i);
        }
    }

    let _ = writeln!(
        out,
        "/// One row per property, sorted by name.\n\
         pub(crate) static ROWS: [Row; {}] = [",
        m.properties.len()
    );
    for p in &m.properties {
        let longhands = if p.longhands.is_empty() {
            "&[]".to_owned()
        } else {
            let items: Vec<String> = p
                .longhands
                .iter()
                .map(|l| format!("Property({})", index.get(l.as_str()).copied().unwrap_or(0)))
                .collect();
            format!("&[{}]", items.join(", "))
        };
        let kind = m.kind_of(p).map_or_else(
            || "None".to_owned(),
            |k| format!("Some(ComputedKind::{})", variant(k)),
        );
        let _ = writeln!(
            out,
            "    Row {{\n        \
             name: {},\n        \
             initial: {},\n        \
             maps_to: {},\n        \
             inherits: {},\n        \
             kind: {},\n        \
             hook: {},\n        \
             affects: {},\n        \
             longhands: {},\n        \
             animation: {},\n    \
             }},",
            string(&p.name),
            opt_string(p.initial.as_ref().or(p.initial_is.as_ref())),
            p.maps_to.as_ref().map_or_else(
                || "None".to_owned(),
                |t| format!(
                    "Some(Property({}))",
                    index.get(t.as_str()).copied().unwrap_or(0)
                )
            ),
            p.inherits.unwrap_or(false),
            kind,
            opt_string(p.hook.as_ref()),
            affects(&p.affects),
            longhands,
            opt_string(p.animation.as_ref()),
        );
    }
    out.push_str("];\n\n");

    out.push_str("impl Property {\n");
    let _ = writeln!(
        out,
        "    /// How many properties `@webref/css` carries at the pinned\n    \
         /// version, not counting the legacy aliases.\n    \
         pub const COUNT: usize = {};\n",
        m.properties.len()
    );
    for (i, p) in m.properties.iter().enumerate() {
        let _ = writeln!(
            out,
            "    /// `{}`\n    pub const {}: Self = Self({i});",
            p.name,
            constant(&p.name)
        );
    }
    out.push_str("}\n\n");

    // The name index: every property and every legacy alias, sorted, so
    // a lookup is a binary search over one table.
    let mut names: Vec<(String, usize)> = m
        .properties
        .iter()
        .enumerate()
        .map(|(i, p)| (p.name.clone(), i))
        .collect();
    for a in &m.aliases {
        names.push((
            a.name.clone(),
            index.get(a.target.as_str()).copied().unwrap_or(0),
        ));
    }
    names.sort();
    let _ = writeln!(
        out,
        "/// Every name a declaration may use — the {} properties and the\n\
         /// {} legacy aliases the Compatibility Standard defines — sorted,\n\
         /// so a lookup is one binary search. An alias resolves to the\n\
         /// property it stands for, which is what the cascade stores.\n\
         pub(crate) static BY_NAME: [(&str, u16); {}] = [",
        m.properties.len(),
        m.aliases.len(),
        names.len()
    );
    for (n, i) in &names {
        let _ = writeln!(out, "    ({}, {i}),", string(n));
    }
    out.push_str("];\n");
    out
}

fn affects(list: &[Affect]) -> String {
    if list.contains(&Affect::Unknown) {
        return "Affects::UNDECIDED".to_owned();
    }
    if list.contains(&Affect::Nothing) {
        return "Affects::NOTHING".to_owned();
    }
    let mut parts = list.iter().map(|a| {
        format!(
            "Affects::{}",
            a.word().replace('-', "_").to_ascii_uppercase()
        )
    });
    let first = parts
        .next()
        .unwrap_or_else(|| "Affects::NOTHING".to_owned());
    parts.fold(first, |acc, p| format!("{acc}.with({p})"))
}

/// `generated/grammars.rs`, behind the `reference` feature.
#[must_use]
pub fn grammars(m: &Model) -> String {
    let mut out = String::new();
    header(
        &mut out,
        "Value grammars and defining URLs, for hg-style-reference and \
         DevTools. Behind the `reference` feature: a site process never \
         reads them.",
        "the .hgprop overlay and @webref/css",
    );
    let _ = writeln!(
        out,
        "/// Each property's value grammar, in CSS value-definition\n\
         /// syntax, indexed as [`super::properties::ROWS`] is. `None`\n\
         /// where the specification states it in a form `@webref/css`\n\
         /// did not extract.\n\
         pub(crate) static GRAMMARS: [Option<&str>; {}] = [",
        m.properties.len()
    );
    for p in &m.properties {
        let _ = writeln!(out, "    {},", opt_string(p.syntax.as_ref()));
    }
    out.push_str("];\n\n");
    let _ = writeln!(
        out,
        "/// Each property's defining URL, indexed the same way.\n\
         pub(crate) static SPEC_URLS: [&str; {}] = [",
        m.properties.len()
    );
    for p in &m.properties {
        let _ = writeln!(out, "    {},", string(&p.href));
    }
    out.push_str("];\n");
    out
}

/// `generated/properties.tsv`: every column in one table, for triage.
#[must_use]
pub fn table(m: &Model) -> String {
    let mut out = String::new();
    out.push_str(
        "# @generated by hg-cssgen. Do not edit.\n\
         # The review table of style spec 6.6: what the overlay says about\n\
         # each property, beside what @webref/css carries. A re-pin is\n\
         # triaged against this (ST-7).\n\
         name\tinherits\tinitial\tfrom\tkind\taffects\tanimation\tmaps-to\tlonghands\thref\tsyntax\n",
    );
    for p in &m.properties {
        let cell = |s: Option<&String>| s.map_or("-", String::as_str).replace(['\t', '\n'], " ");
        let _ = writeln!(
            out,
            "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}",
            p.name,
            p.inherits.map_or("-", |b| if b { "yes" } else { "no" }),
            cell(p.initial.as_ref().or(p.initial_is.as_ref())),
            if p.initial.is_some() {
                "webref"
            } else if p.initial_is.is_some() {
                "izcal"
            } else {
                "-"
            },
            m.kind_of(p).unwrap_or("-"),
            p.affects
                .iter()
                .map(|a| a.word())
                .collect::<Vec<_>>()
                .join("+"),
            cell(p.animation.as_ref()),
            p.maps_to.as_deref().unwrap_or("-"),
            if p.longhands.is_empty() {
                "-".to_owned()
            } else {
                p.longhands.join(" ")
            },
            p.href,
            cell(p.syntax.as_ref()),
        );
    }
    for a in &m.aliases {
        let _ = writeln!(out, "{}\t-\t-\talias\t-\t-\t-\t{}\t-", a.name, a.target);
    }
    out
}

/// Every constant name the table will carry, with the property it came
/// from, so a collision is caught rather than compiled.
#[must_use]
pub fn constants(m: &Model) -> Vec<(String, &PropertyDecl)> {
    m.properties
        .iter()
        .map(|p| (constant(&p.name), p))
        .collect()
}
