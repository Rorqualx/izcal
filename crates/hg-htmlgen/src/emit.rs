fn test(m: &Match) -> String {
    match m {
        Match::Char(c) => format!("input == Some({})", ch(*c)),
        Match::Eof => "input.is_none()".to_owned(),
        Match::Class(Class::Null) => "input == Some('\\0')".to_owned(),
        Match::Class(c) => format!("input.is_some_and(|c| {})", c.test()),
        Match::OneOf(ms) => ms
            .iter()
            .map(|x| format!("({})", test(x)))
            .collect::<Vec<_>>()
            .join(" || "),
        Match::Lookahead(l) => {
            let f = if l.from_current {
                "match_from"
            } else {
                "match_next"
            };
            format!("self.{f}({:?}, {})", l.text, l.ci)
        }
        Match::Anything => "true".to_owned(),
    }
}

fn run(out: &mut String, actions: &[Action], indent: &str) {
    for a in actions {
        match a {
            Action::Switch(s) => {
                let _ = writeln!(out, "{indent}self.switch(State::{});", camel(s));
            }
            Action::Reconsume(s) => {
                let _ = writeln!(out, "{indent}self.reconsume_in(State::{});", camel(s));
            }
            Action::SetReturn(s) => {
                let _ = writeln!(out, "{indent}self.set_return(State::{});", camel(s));
            }
            Action::SwitchReturn => {
                let _ = writeln!(out, "{indent}self.switch_return();");
            }
            Action::ReconsumeReturn => {
                let _ = writeln!(out, "{indent}self.reconsume_return();");
            }
            Action::EmitCurrent => {
                let _ = writeln!(out, "{indent}self.emit_current();");
            }
            Action::EmitChar(c) => {
                let _ = writeln!(out, "{indent}self.emit_char({});", ch(*c));
            }
            Action::EmitEof => {
                let _ = writeln!(out, "{indent}self.emit_eof();");
            }
            Action::EmitToken => {
                let _ = writeln!(out, "{indent}self.emit_token();");
            }
            Action::EmitTemp => {
                let _ = writeln!(out, "{indent}self.emit_temp();");
            }
            Action::CreateStartTag => {
                let _ = writeln!(out, "{indent}self.create_tag(false);");
            }
            Action::CreateEndTag => {
                let _ = writeln!(out, "{indent}self.create_tag(true);");
            }
            Action::CreateComment => {
                let _ = writeln!(out, "{indent}self.create_comment();");
            }
            Action::CreateDoctype => {
                let _ = writeln!(out, "{indent}self.create_doctype();");
            }
            Action::CreatePi => {
                let _ = writeln!(out, "{indent}self.create_pi();");
            }
            Action::TempToComment => {
                let _ = writeln!(out, "{indent}self.temp_to_comment();");
            }
            Action::StartAttribute => {
                let _ = writeln!(out, "{indent}self.start_attribute();");
            }
            Action::Append(b) => {
                let _ = writeln!(out, "{indent}self.push_current(Buf::{});", buf_variant(*b));
            }
            Action::AppendLower(b) => {
                let _ = writeln!(
                    out,
                    "{indent}self.push_current_lower(Buf::{});",
                    buf_variant(*b)
                );
            }
            Action::AppendChar(b, c) => {
                let _ = writeln!(
                    out,
                    "{indent}self.push(Buf::{}, {});",
                    buf_variant(*b),
                    ch(*c)
                );
            }
            Action::AppendStr(b, s) => {
                let _ = writeln!(
                    out,
                    "{indent}self.push_str(Buf::{}, {s:?});",
                    buf_variant(*b)
                );
            }
            Action::ClearTemp => {
                let _ = writeln!(out, "{indent}self.clear_temp();");
            }
            Action::FlushTemp => {
                let _ = writeln!(out, "{indent}self.flush_temp();");
            }
            Action::Set(f) => {
                let _ = writeln!(out, "{indent}self.set_flag(Flag::{});", flag_variant(*f));
            }
            Action::Ignore => {
                let _ = writeln!(out, "{indent}// \"Ignore the character.\"");
            }
            Action::CharRefReset => {
                let _ = writeln!(out, "{indent}self.char_ref_reset();");
            }
            Action::CharRefHexDigit => {
                let _ = writeln!(out, "{indent}self.char_ref_digit(16);");
            }
            Action::CharRefDecDigit => {
                let _ = writeln!(out, "{indent}self.char_ref_digit(10);");
            }
            Action::FinishAttrName => {
                let _ = writeln!(out, "{indent}self.finish_attr_name();");
            }
            Action::Error(n) => {
                let _ = writeln!(out, "{indent}self.error({n:?});");
            }
            Action::If {
                cond,
                then,
                otherwise,
            } => {
                let _ = writeln!(
                    out,
                    "{indent}if self.test(Cond::{}) {{",
                    cond_variant(*cond)
                );
                run(out, then, &format!("{indent}    "));
                let _ = writeln!(out, "{indent}}} else {{");
                run(out, otherwise, &format!("{indent}    "));
                let _ = writeln!(out, "{indent}}}");
            }
        }
    }
}

/// The tokenizer: one function per state.
#[must_use]
pub fn tokenizer(m: &Model) -> String {
    let mut out = header("The tokenizer. One function per state, every rule an `if`.");
    out.push_str(
        "//! The tokenizer, compiled from the descriptions.\n\
         //!\n\
         //! Every rule is an `if` in the prose's order and every action a\n\
         //! call on the runtime, so a state reads beside the clause its\n\
         //! anchor names.\n\n\
         use crate::State;\n\
         use crate::table::{Buf, Cond, Flag};\n\
         use crate::token::Sink;\n\
         use crate::tokenizer::Tokenizer;\n\n",
    );
    out.push_str("impl<S: Sink> Tokenizer<S> {\n");
    out.push_str("    /// One state.\n");
    out.push_str("    pub(crate) fn generated_step(&mut self) {\n");
    out.push_str("        match self.state() {\n");
    for s in &m.states {
        if s.external {
            let _ = writeln!(
                out,
                "            State::{} => self.external_state(),",
                camel(&s.name)
            );
        } else {
            let _ = writeln!(
                out,
                "            State::{} => self.{}(),",
                camel(&s.name),
                fn_name(&s.name)
            );
        }
    }
    out.push_str("        }\n    }\n\n");

    for s in &m.states {
        if s.external {
            continue;
        }
        let _ = writeln!(out, "    /// The `{}` state, at `{}`.", s.name, s.anchor);
        let _ = writeln!(out, "    fn {}(&mut self) {{", fn_name(&s.name));
        run(&mut out, &s.enter, "        ");
        let consume = consumes(s);
        if consume {
            let uses_input = s
                .rules
                .iter()
                .any(|r| !matches!(r.matches, Match::Anything));
            if uses_input {
                out.push_str("        let input = self.consume();\n");
            } else {
                out.push_str("        self.consume();\n");
            }
        }
        // One `if … else if … else` chain, in the prose's order. A
        // chain rather than early returns because a lookahead test
        // consumes when it matches, so it must be reached only when
        // every earlier row has failed — and because the last row's
        // body is sometimes "Ignore the character", which leaves
        // nothing for a `return` to precede.
        let mut first = true;
        for r in &s.rules {
            if let Some(a) = &r.anchor {
                let _ = writeln!(out, "        // {a}");
            }
            if matches!(r.matches, Match::Anything) {
                if first {
                    out.push_str("        // \"Anything else\"\n");
                    run(&mut out, &r.actions, "        ");
                } else {
                    out.push_str("        } else {\n            // \"Anything else\"\n");
                    run(&mut out, &r.actions, "            ");
                    out.push_str("        }\n");
                }
            } else {
                let keyword = if first { "if" } else { "} else if" };
                let _ = writeln!(out, "        {keyword} {} {{", test(&r.matches));
                run(&mut out, &r.actions, "            ");
            }
            first = false;
        }
        if !s
            .rules
            .last()
            .is_some_and(|r| matches!(r.matches, Match::Anything))
        {
            out.push_str("        }\n");
        }
        out.push_str("    }\n\n");
    }
    out.push_str("}\n");
    out
}

fn fn_name(name: &str) -> String {
    format!("st_{name}")
}

