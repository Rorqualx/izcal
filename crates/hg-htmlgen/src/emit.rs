/// Every transition, as the coverage table ANC-1 and the fuzzers read.
#[must_use]
pub fn transitions(m: &Model) -> String {
    let mut out =
        String::from("# @generated by hg-htmlgen. Every transition the descriptions declare.\n");
    out.push_str("# from\tto\n");
    for (from, to) in &m.transitions {
        let _ = writeln!(out, "{from}\t{to}");
    }
    out
}

/// Every anchor, one per line.
#[must_use]
pub fn anchors(m: &Model) -> String {
    let mut out = String::from("# @generated by hg-htmlgen. Anchors, one per line.\n");
    for a in &m.anchors {
        let _ = writeln!(out, "{a}");
    }
    out
}

