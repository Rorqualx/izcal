/// The named character references, as a sorted table and a binary
/// search over it.
///
/// `names` maps each identifier *without* its leading ampersand to the
/// one or two characters it stands for: the tokenizer has consumed the
/// ampersand before it reaches the named character reference state.
#[must_use]
pub fn entities(names: &BTreeMap<String, String>) -> String {
    let mut out = header("The named character references, from WHATWG's entities.json.");
    out.push_str(
        "//! The named character reference table (HTML §13.5), compiled\n\
         //! from WHATWG's `entities.json`: standards data, pinned by its\n\
         //! own content hash in tools/test-data.toml.\n\
         //!\n\
         //! Names are stored without their leading ampersand, which the\n\
         //! tokenizer has already consumed, and sorted, so the named\n\
         //! character reference state's longest match is a binary search\n\
         //! per prefix length.\n\n",
    );
    let longest = names.keys().map(|k| k.chars().count()).max().unwrap_or(0);
    let _ = writeln!(
        out,
        "/// The longest identifier, in characters: how far the longest\n\
         /// match has to look.\npub const LONGEST_NAME: usize = {longest};\n"
    );
    let _ = writeln!(
        out,
        "/// How many identifiers there are.\npub const COUNT: usize = {};\n",
        names.len()
    );
    out.push_str(
        "/// Sorted by name, so [`lookup`] can binary search it.\n\
         pub static NAMES: [(&str, &str); COUNT] = [\n",
    );
    for (k, v) in names {
        let _ = writeln!(out, "    ({k:?}, {v:?}),");
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// The characters `name` stands for, or `None` when it is not an\n\
         /// identifier.\n\
         #[must_use]\n\
         pub fn lookup(name: &str) -> Option<&'static str> {\n\
        \x20   NAMES\n\
        \x20       .binary_search_by(|(k, _)| (*k).cmp(name))\n\
        \x20       .ok()\n\
        \x20       .and_then(|i| NAMES.get(i))\n\
        \x20       .map(|(_, v)| *v)\n\
         }\n",
    );
    out
}
