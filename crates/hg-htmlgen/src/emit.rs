//! Emitting `hg-html-syntax` from a checked model.
//!
//! Two back ends from the one description (style spec 6.2, ST-D3):
//!
//! - [`tokenizer`] writes plain Rust — one function per state, every
//!   rule an `if`, every action a call;
//! - [`states`] writes the same model as *data*, which the runtime's
//!   reference stepper interprets.
//!
//! They share the description and no code, so a mistake in the
//! description appears in both (html5lib catches that) while a mistake
//! in the generator appears in one (comparing them catches that).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::check::Model;
use crate::syntax::{Action, Buffer, Class, Cond, Flag, Lookahead, Match, State};

fn header(what: &str) -> String {
    format!(
        "// @generated by hg-htmlgen from the .hgtok descriptions in \
         crates/hg-html-syntax/states.\n// Do not edit: change the descriptions and run \
         `cargo run -p hg-htmlgen -- generate`.\n// {what}\n\n"
    )
}

/// `tag_open` becomes `TagOpen`.
#[must_use]
pub fn camel(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('_') {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            out.push_str(cs.as_str());
        }
    }
    out
}

/// A Rust character literal for `c`.
#[must_use]
pub fn ch(c: char) -> String {
    match c {
        '\'' => "'\\''".to_owned(),
        '\\' => "'\\\\'".to_owned(),
        '\n' => "'\\n'".to_owned(),
        '\t' => "'\\t'".to_owned(),
        '\r' => "'\\r'".to_owned(),
        '\0' => "'\\0'".to_owned(),
        c if c.is_ascii_graphic() || c == ' ' => format!("'{c}'"),
        c => format!("'\\u{{{:04X}}}'", u32::from(c)),
    }
}

const fn class_variant(c: Class) -> &'static str {
    match c {
        Class::Whitespace => "Whitespace",
        Class::Null => "Null",
        Class::AsciiAlpha => "AsciiAlpha",
        Class::AsciiUpper => "AsciiUpper",
        Class::AsciiLower => "AsciiLower",
        Class::AsciiDigit => "AsciiDigit",
        Class::AsciiHexDigit => "AsciiHexDigit",
        Class::AsciiAlphanumeric => "AsciiAlphanumeric",
    }
}

const fn buf_variant(b: Buffer) -> &'static str {
    match b {
        Buffer::TagName => "TagName",
        Buffer::AttrName => "AttrName",
        Buffer::AttrValue => "AttrValue",
        Buffer::Comment => "Comment",
        Buffer::DoctypeName => "DoctypeName",
        Buffer::PublicId => "PublicId",
        Buffer::SystemId => "SystemId",
        Buffer::Temp => "Temp",
        Buffer::PiData => "PiData",
    }
}

const fn flag_variant(f: Flag) -> &'static str {
    match f {
        Flag::SelfClosing => "SelfClosing",
        Flag::ForceQuirks => "ForceQuirks",
        Flag::PublicIdEmpty => "PublicIdEmpty",
        Flag::SystemIdEmpty => "SystemIdEmpty",
    }
}

const fn cond_variant(c: Cond) -> &'static str {
    match c {
        Cond::Appropriate => "Appropriate",
        Cond::TempIsScript => "TempIsScript",
        Cond::DisallowedPiTarget => "DisallowedPiTarget",
        Cond::InAttribute => "InAttribute",
        Cond::AdjustedNotHtml => "AdjustedNotHtml",
    }
}

/// Whether the state consumes a character before testing its rules.
fn consumes(s: &State) -> bool {
    !s.rules.iter().any(|r| r.matches.looks_ahead_unconsumed())
}

// ---------------------------------------------------------------------
// The reference stepper's table.
// ---------------------------------------------------------------------

fn pat(m: &Match) -> String {
    match m {
        Match::Char(c) => format!("Pat::Char({})", ch(*c)),
        Match::Class(c) => format!("Pat::Class(Class::{})", class_variant(*c)),
        Match::Eof => "Pat::Eof".to_owned(),
        Match::Anything => "Pat::Anything".to_owned(),
        Match::OneOf(ms) => {
            let inner: Vec<String> = ms.iter().map(pat).collect();
            format!("Pat::OneOf(&[{}])", inner.join(", "))
        }
        Match::Lookahead(Lookahead {
            text,
            from_current,
            ci,
        }) => {
            format!("Pat::Lookahead {{ text: {text:?}, from_current: {from_current}, ci: {ci} }}")
        }
    }
}

fn op(a: &Action) -> String {
    match a {
        Action::Switch(s) => format!("Op::Switch(State::{})", camel(s)),
        Action::Reconsume(s) => format!("Op::Reconsume(State::{})", camel(s)),
        Action::SetReturn(s) => format!("Op::SetReturn(State::{})", camel(s)),
        Action::SwitchReturn => "Op::SwitchReturn".to_owned(),
        Action::ReconsumeReturn => "Op::ReconsumeReturn".to_owned(),
        Action::EmitCurrent => "Op::EmitCurrent".to_owned(),
        Action::EmitChar(c) => format!("Op::EmitChar({})", ch(*c)),
        Action::EmitEof => "Op::EmitEof".to_owned(),
        Action::EmitToken => "Op::EmitToken".to_owned(),
        Action::EmitTemp => "Op::EmitTemp".to_owned(),
        Action::CreateStartTag => "Op::CreateStartTag".to_owned(),
        Action::CreateEndTag => "Op::CreateEndTag".to_owned(),
        Action::CreateComment => "Op::CreateComment".to_owned(),
        Action::CreateDoctype => "Op::CreateDoctype".to_owned(),
        Action::CreatePi => "Op::CreatePi".to_owned(),
        Action::TempToComment => "Op::TempToComment".to_owned(),
        Action::StartAttribute => "Op::StartAttribute".to_owned(),
        Action::Append(b) => format!("Op::Append(Buf::{})", buf_variant(*b)),
        Action::AppendLower(b) => format!("Op::AppendLower(Buf::{})", buf_variant(*b)),
        Action::AppendChar(b, c) => {
            format!("Op::AppendChar(Buf::{}, {})", buf_variant(*b), ch(*c))
        }
        Action::AppendStr(b, s) => format!("Op::AppendStr(Buf::{}, {s:?})", buf_variant(*b)),
        Action::ClearTemp => "Op::ClearTemp".to_owned(),
        Action::FlushTemp => "Op::FlushTemp".to_owned(),
        Action::Set(f) => format!("Op::Set(Flag::{})", flag_variant(*f)),
        Action::Ignore => "Op::Ignore".to_owned(),
        Action::CharRefReset => "Op::CharRefReset".to_owned(),
        Action::CharRefHexDigit => "Op::CharRefHexDigit".to_owned(),
        Action::CharRefDecDigit => "Op::CharRefDecDigit".to_owned(),
        Action::FinishAttrName => "Op::FinishAttrName".to_owned(),
        Action::Error(n) => format!("Op::Error({n:?})"),
        Action::If {
            cond,
            then,
            otherwise,
        } => format!(
            "Op::If {{ cond: Cond::{}, then: &[{}], otherwise: &[{}] }}",
            cond_variant(*cond),
            ops(then),
            ops(otherwise)
        ),
    }
}

fn ops(actions: &[Action]) -> String {
    actions.iter().map(op).collect::<Vec<_>>().join(", ")
}

/// The `State` and `EntryState` enums and the stepper's table.
#[must_use]
pub fn states(m: &Model) -> String {
    let mut out = header("The states, and the reference stepper's table.");
    out.push_str(
        "//! The tokenizer's states, and the table the reference stepper\n\
         //! interprets.\n\n\
         use crate::table::{Buf, Class, Cond, Flag, Op, Pat, Rule, StateDesc};\n\n",
    );

    out.push_str("/// Every state of the tokenizer, in the order the descriptions\n");
    out.push_str("/// declare them, which is the standard's own order.\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    out.push_str("pub enum State {\n");
    for s in &m.states {
        let _ = writeln!(out, "    /// `{}`, at `{}`.", s.name, s.anchor);
        let _ = writeln!(out, "    {},", camel(&s.name));
    }
    out.push_str("}\n\n");

    out.push_str("impl State {\n");
    out.push_str("    /// Its description, which the reference stepper reads.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub const fn desc(self) -> &'static StateDesc {\n");
    out.push_str("        match self {\n");
    for s in &m.states {
        let _ = writeln!(
            out,
            "            Self::{} => &{},",
            camel(&s.name),
            static_name(&s.name)
        );
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// Its name, as the description writes it.\n");
    out.push_str("    #[must_use]\n");
    out.push_str(
        "    pub const fn name(self) -> &'static str {\n        self.desc().name\n    }\n\n",
    );
    out.push_str("    /// The clause that defines it.\n");
    out.push_str("    #[must_use]\n");
    out.push_str(
        "    pub const fn anchor(self) -> &'static str {\n        self.desc().anchor\n    }\n",
    );
    out.push_str("}\n\n");

    out.push_str(
        "/// The states the tree construction stage may switch the tokenizer\n\
         /// into — \"switch the tokenizer to the RAWTEXT state\" and its\n\
         /// siblings. It can name these and no others.\n",
    );
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    out.push_str("pub enum EntryState {\n");
    for s in m.states.iter().filter(|s| s.entry) {
        let _ = writeln!(out, "    /// `{}`.", s.name);
        let _ = writeln!(out, "    {},", camel(&s.name));
    }
    out.push_str("}\n\n");
    out.push_str(
        "/// The states whose implementation is hand-written, because the\n\
         /// prose does not write them as a per-character table. The runtime\n\
         /// matches on this, so adding one to a description fails to compile\n\
         /// until it is implemented.\n",
    );
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    out.push_str("pub enum Extern {\n");
    for s in m.states.iter().filter(|s| s.external) {
        let _ = writeln!(out, "    /// `{}`.", s.name);
        let _ = writeln!(out, "    {},", camel(&s.name));
    }
    out.push_str("}\n\n");
    out.push_str("impl State {\n");
    out.push_str("    /// Which hand-written state this is, if it is one.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub const fn external(self) -> Option<Extern> {\n        match self {\n");
    for s in &m.states {
        if s.external {
            let _ = writeln!(
                out,
                "            Self::{} => Some(Extern::{0}),",
                camel(&s.name)
            );
        } else {
            let _ = writeln!(out, "            Self::{} => None,", camel(&s.name));
        }
    }
    out.push_str("        }\n    }\n}\n\n");
    let _ = writeln!(
        out,
        "/// Every state, so a check over all of them joins by existing.\n\
         pub const ALL: [State; {}] = [",
        m.states.len()
    );
    for s in &m.states {
        let _ = writeln!(out, "    State::{},", camel(&s.name));
    }
    out.push_str("];\n\n");
    out.push_str("impl EntryState {\n");
    out.push_str("    /// The state it names.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub const fn state(self) -> State {\n        match self {\n");
    for s in m.states.iter().filter(|s| s.entry) {
        let _ = writeln!(out, "            Self::{0} => State::{0},", camel(&s.name));
    }
    out.push_str("        }\n    }\n}\n\n");

    for s in &m.states {
        let _ = writeln!(
            out,
            "static {}: StateDesc = StateDesc {{",
            static_name(&s.name)
        );
        let _ = writeln!(out, "    name: {:?},", s.name);
        let _ = writeln!(out, "    anchor: {:?},", s.anchor);
        let _ = writeln!(out, "    external: {},", s.external);
        let _ = writeln!(out, "    entry: {},", s.entry);
        let _ = writeln!(out, "    consumes: {},", consumes(s));
        let _ = writeln!(out, "    enter: &[{}],", ops(&s.enter));
        out.push_str("    rules: &[\n");
        for r in &s.rules {
            let anchor = r
                .anchor
                .as_ref()
                .map_or_else(|| "None".to_owned(), |a| format!("Some({a:?})"));
            let _ = writeln!(
                out,
                "        Rule {{ pat: {}, ops: &[{}], anchor: {anchor} }},",
                pat(&r.matches),
                ops(&r.actions)
            );
        }
        out.push_str("    ],\n};\n\n");
    }
    out
}

fn static_name(name: &str) -> String {
    format!("S_{}", name.to_uppercase())
}

