//! Writing `hg-encoding`'s tables from the Encoding Standard's data.
//!
//! Two outputs:
//!
//! - `generated/encodings.rs` — the [`Encoding`](crate::data::Encoding)
//!   enum, its names, and the label table the standard's "get an
//!   encoding" searches.
//! - `generated/indexes.rs` — every index, in both directions.
//!
//! **Both directions, because the standard says so.** Section 5: "An
//! efficient implementation likely has two indexes per encoding. One
//! optimized for its decoder and one for its encoder." The decode
//! direction is the index as published, read by pointer. The encode
//! direction is sorted by code point, and the three pointer algorithms
//! the standard defines — *index pointer*, *index Shift_JIS pointer*
//! and *index Big5 pointer* — are applied **here**, once, rather than
//! in the encoder, so the runtime is a binary search and the rules are
//! in one place where they can be read against the prose.
//!
//! The large tables carry `#[rustfmt::skip]` and sixteen values to the
//! line. One value per line, which is this repository's style for a
//! table of pairs, would be 150,000 lines for data that is read by
//! index and never by eye.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::data::{Data, Encoding, Index};

/// The header every generated file carries.
fn header(out: &mut String, what: &str) {
    let _ = writeln!(
        out,
        "// @generated by hg-encoding-build from the Encoding Standard's\n\
         // encodings.json and indexes.json. Do not edit: run\n\
         // `cargo run -p hg-encoding-build -- generate`.\n\
         //\n\
         //! {what}\n"
    );
}

/// The Rust variant name for an encoding: `ISO-8859-8-I` becomes
/// `Iso8859_8I`, `x-mac-cyrillic` becomes `XMacCyrillic`.
#[must_use]
pub fn variant(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    let mut upper = true;
    for (i, c) in chars.iter().enumerate() {
        if *c == '-' || *c == '_' {
            // A separator between two digits has to survive, or
            // `ISO-8859-2` and `ISO-88592` would be one name. Between a
            // digit and a letter it need not, so `ISO-2022-JP` stays
            // readable.
            let before = i.checked_sub(1).and_then(|j| chars.get(j));
            let after = chars.get(i.saturating_add(1));
            if before.is_some_and(char::is_ascii_digit) && after.is_some_and(char::is_ascii_digit) {
                out.push('_');
            }
            upper = true;
            continue;
        }
        if upper {
            out.push(c.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(c.to_ascii_lowercase());
        }
    }
    out
}

/// `generated/encodings.rs`.
#[must_use]
pub fn encodings(d: &Data) -> String {
    let mut out = String::new();
    header(
        &mut out,
        "The encodings the Encoding Standard defines, and their labels.",
    );
    out.push_str(
        "/// One of the encodings the Encoding Standard defines.\n\
         ///\n\
         /// The standard is exhaustive and has no mechanism for\n\
         /// extension (Section 1), so this list is closed: every match\n\
         /// over it is exhaustive, and an encoding added to a future\n\
         /// revision breaks each one until it is handled.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum Encoding {\n",
    );
    for e in &d.encodings {
        let _ = writeln!(
            out,
            "    /// `{}` ({}).\n    {},",
            e.name,
            e.group.to_lowercase(),
            variant(&e.name)
        );
    }
    out.push_str("}\n\nimpl Encoding {\n");
    let _ = writeln!(
        out,
        "    /// Every encoding, in the order the standard lists them.\n    \
         pub const ALL: [Self; {}] = [",
        d.encodings.len()
    );
    for e in &d.encodings {
        let _ = writeln!(out, "        Self::{},", variant(&e.name));
    }
    out.push_str("    ];\n\n");
    out.push_str(
        "    /// Its name, in the standard's own spelling. This is what\n\
         \x20   /// `TextDecoder`'s `encoding` attribute returns, lower\n\
         \x20   /// cased.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn name(self) -> &'static str {\n\
         \x20       match self {\n",
    );
    for e in &d.encodings {
        let _ = writeln!(
            out,
            "            Self::{} => {:?},",
            variant(&e.name),
            e.name
        );
    }
    out.push_str("        }\n    }\n}\n\n");

    // The decoder and encoder each encoding uses. Twenty-eight of the
    // forty share the single-byte pair, and the rest are their own, so
    // the runtime matches on thirteen families rather than on forty
    // names -- and exhaustively, because this crate denies
    // `wildcard_enum_match_arm`.
    let family = |e: &Encoding| -> String {
        if e.group.contains("single-byte") {
            "SingleByte".to_owned()
        } else {
            variant(&e.name)
        }
    };
    let mut families: Vec<String> = d.encodings.iter().map(family).collect();
    families.sort();
    families.dedup();
    out.push_str(
        "/// Which decoder and encoder an encoding uses.\n\
         ///\n\
         /// Twenty-eight of the forty encodings share the single-byte\n\
         /// decoder and encoder, differing only in their index\n\
         /// (Section 9), so they share one family.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum Family {\n",
    );
    for f in &families {
        let _ = writeln!(out, "    /// The `{f}` decoder and encoder.\n    {f},");
    }
    out.push_str("}\n\nimpl Encoding {\n");
    out.push_str(
        "    /// The decoder and encoder it uses.\n\
         \x20   #[must_use]\n\
         \x20   pub const fn family(self) -> Family {\n\
         \x20       match self {\n",
    );
    for e in &d.encodings {
        let _ = writeln!(
            out,
            "            Self::{} => Family::{},",
            variant(&e.name),
            family(e)
        );
    }
    out.push_str("        }\n    }\n}\n\n");

    let mut labels: Vec<(&str, String)> = Vec::new();
    for e in &d.encodings {
        for l in &e.labels {
            labels.push((l.as_str(), variant(&e.name)));
        }
    }
    labels.sort();
    let _ = writeln!(
        out,
        "/// Every label, sorted, with the encoding it selects.\n\
         ///\n\
         /// The standard's labels are all ASCII lower case already, and\n\
         /// \"get an encoding\" strips leading and trailing whitespace and\n\
         /// compares ASCII case-insensitively, so one binary search over\n\
         /// this answers it.\n\
         pub static LABELS: [(&str, Encoding); {}] = [",
        labels.len()
    );
    for (l, v) in &labels {
        let _ = writeln!(out, "    ({l:?}, Encoding::{v}),");
    }
    out.push_str("];\n");
    out
}

/// A flat table of numbers, sixteen to the line.
fn flat(out: &mut String, doc: &str, name: &str, ty: &str, values: &[String]) {
    let _ = writeln!(
        out,
        "/// {doc}\n#[rustfmt::skip]\npub static {name}: [{ty}; {}] = [",
        values.len()
    );
    for row in values.chunks(16) {
        let _ = writeln!(out, "    {}", row.join(", ") + ",");
    }
    out.push_str("];\n\n");
}

/// A table of pairs, eight to the line.
fn pairs(out: &mut String, doc: &str, name: &str, ty: &str, values: &[(u32, u32)]) {
    let _ = writeln!(
        out,
        "/// {doc}\n#[rustfmt::skip]\npub static {name}: [({ty}, u16); {}] = [",
        values.len()
    );
    let cells: Vec<String> = values
        .iter()
        .map(|(a, b)| format!("({a:#X}, {b})"))
        .collect();
    for row in cells.chunks(8) {
        let _ = writeln!(out, "    {}", row.join(", ") + ",");
    }
    out.push_str("];\n\n");
}

/// The `none` marker in a decode table: no index has an entry for it.
const NONE16: u16 = u16::MAX;
/// The same, for the one table whose code points reach beyond U+FFFF.
const NONE32: u32 = u32::MAX;

fn points(d: &Data, name: &str) -> Result<Vec<Option<u32>>, String> {
    match d.indexes.get(name) {
        Some(Index::Points(p)) => Ok(p.clone()),
        Some(Index::Ranges(_)) => Err(format!("index {name} is ranges, not code points")),
        None => Err(format!("indexes.json has no index {name}")),
    }
}

/// The *index pointer* of the standard's Section 5: the first pointer
/// for each code point, over the entries `keep` accepts.
fn first_pointers(index: &[Option<u32>], keep: impl Fn(usize) -> bool) -> Vec<(u32, u32)> {
    let mut seen: BTreeMap<u32, u32> = BTreeMap::new();
    for (p, cp) in index.iter().enumerate() {
        let (Some(cp), true) = (cp, keep(p)) else {
            continue;
        };
        let Ok(p) = u32::try_from(p) else { continue };
        seen.entry(*cp).or_insert(p);
    }
    seen.into_iter().collect()
}

/// `generated/indexes.rs`.
///
/// # Errors
/// A message when an index the standard defines is missing from the
/// data, or holds a value the chosen table type cannot carry.
pub fn indexes(d: &Data) -> Result<String, String> {
    let mut out = String::new();
    header(
        &mut out,
        "The Encoding Standard's indexes, in both directions.",
    );
    out.push_str("use super::encodings::Encoding;\n\n");
    let _ = writeln!(
        out,
        "/// No entry. The standard's indexes reach U+FFE6 at most in\n\
         /// every table but Big5, so `u16::MAX` is free to mean \"none\".\n\
         pub const NONE16: u16 = u16::MAX;\n\n\
         /// The same, for Big5, whose entries reach U+2F9D4.\n\
         pub const NONE32: u32 = u32::MAX;\n"
    );

    // --- the single-byte indexes, decode and encode -------------------
    let mut single: Vec<(String, String)> = Vec::new();
    for e in &d.encodings {
        if !e.group.contains("single-byte") {
            continue;
        }
        // ISO-8859-8-I shares ISO-8859-8's index: the standard gives it
        // no index of its own, the two differ only in bidi handling.
        let key = if e.name == "ISO-8859-8-I" {
            "iso-8859-8".to_owned()
        } else {
            e.name.to_lowercase()
        };
        let index = points(d, &key)?;
        if index.len() != 128 {
            return Err(format!("index {key} has {} entries, not 128", index.len()));
        }
        let upper = variant(&e.name).to_uppercase();
        if e.name != "ISO-8859-8-I" {
            let cells: Vec<String> = index
                .iter()
                .map(|c| {
                    c.map_or_else(
                        || "NONE16".to_owned(),
                        |v| {
                            if v >= u32::from(NONE16) {
                                format!("{v:#X}")
                            } else {
                                format!("{v:#06X}")
                            }
                        },
                    )
                })
                .collect();
            flat(
                &mut out,
                &format!("`index {}`, by pointer: byte − 0x80.", e.name),
                &upper,
                "u16",
                &cells,
            );
            let enc = first_pointers(&index, |_| true);
            pairs(
                &mut out,
                &format!("`index {}` by code point, with its pointer.", e.name),
                &format!("{upper}_ENCODE"),
                "u16",
                &enc,
            );
        }
        let table = if e.name == "ISO-8859-8-I" {
            "ISO8859_8".to_owned()
        } else {
            upper
        };
        single.push((variant(&e.name), table));
    }
    let lookup: BTreeMap<&str, &str> = single
        .iter()
        .map(|(v, t)| (v.as_str(), t.as_str()))
        .collect();
    for (what, doc, ty, suffix) in [
        (
            "single_byte",
            "The decode table of a single-byte encoding, by pointer.\n\
             ///\n\
             /// `None` for every encoding that is not single-byte, so a\n\
             /// caller cannot reach a table that is not there.",
            "&'static [u16; 128]",
            "",
        ),
        (
            "single_byte_encode",
            "The encode table of a single-byte encoding, by code point.",
            "&'static [(u16, u16)]",
            "_ENCODE",
        ),
    ] {
        let _ = writeln!(
            out,
            "/// {doc}\n#[must_use]\npub const fn {what}(e: Encoding) -> Option<{ty}> {{\n    \
             match e {{"
        );
        // Every variant, not a wildcard: this crate denies
        // `wildcard_enum_match_arm`, and an encoding added to a future
        // revision of the standard should break this rather than
        // silently answer `None`.
        for e in &d.encodings {
            let v = variant(&e.name);
            match lookup.get(v.as_str()) {
                Some(t) => {
                    let _ = writeln!(out, "        Encoding::{v} => Some(&{t}{suffix}),");
                }
                None => {
                    let _ = writeln!(out, "        Encoding::{v} => None,");
                }
            }
        }
        out.push_str("    }\n}\n\n");
    }

    // --- the multi-byte indexes ---------------------------------------
    for (key, name, doc) in [
        (
            "gb18030",
            "GB18030",
            "`index gb18030`, by pointer (Section 5).",
        ),
        ("euc-kr", "EUC_KR", "`index EUC-KR`, by pointer."),
        ("jis0208", "JIS0208", "`index jis0208`, by pointer."),
        (
            "jis0212",
            "JIS0212",
            "`index jis0212`, by pointer. Decoding only: EUC-JP reads it \
             and nothing writes it.",
        ),
        (
            "iso-2022-jp-katakana",
            "ISO2022JP_KATAKANA",
            "`index ISO-2022-JP katakana`, by pointer. Used by the \
             ISO-2022-JP *encoder* only.",
        ),
    ] {
        let index = points(d, key)?;
        let mut cells = Vec::new();
        for c in &index {
            match c {
                None => cells.push("NONE16".to_owned()),
                Some(v) if *v < u32::from(NONE16) => cells.push(format!("{v:#06X}")),
                Some(v) => return Err(format!("index {key} has {v:#X}, which u16 cannot hold")),
            }
        }
        flat(&mut out, doc, name, "u16", &cells);
    }

    let big5 = points(d, "big5")?;
    let mut cells = Vec::new();
    for c in &big5 {
        match c {
            None => cells.push("NONE32".to_owned()),
            Some(v) if *v < NONE32 => cells.push(format!("{v:#06X}")),
            Some(v) => return Err(format!("index big5 has {v:#X}, which u32 cannot hold")),
        }
    }
    flat(
        &mut out,
        "`index Big5`, by pointer. The one index whose code points reach \
         beyond U+FFFF, so the one held as `u32`.",
        "BIG5",
        "u32",
        &cells,
    );

    let Some(Index::Ranges(ranges)) = d.indexes.get("gb18030-ranges") else {
        return Err("indexes.json has no index gb18030-ranges".to_owned());
    };
    let cells: Vec<String> = ranges
        .iter()
        .map(|(p, c)| format!("({p}, {c:#X})"))
        .collect();
    let _ = writeln!(
        out,
        "/// `index gb18030 ranges`: (pointer, code point), ascending in\n\
         /// both. Listing every code point would be over a million\n\
         /// entries; 207 ranges and two limit checks do the same work\n\
         /// (Section 5).\n\
         #[rustfmt::skip]\n\
         pub static GB18030_RANGES: [(u32, u32); {}] = [",
        ranges.len()
    );
    for row in cells.chunks(6) {
        let _ = writeln!(out, "    {}", row.join(", ") + ",");
    }
    out.push_str("];\n\n");

    // --- the encode directions, with the standard's pointer rules -----
    pairs(
        &mut out,
        "`index pointer` over `index gb18030`, by code point.",
        "GB18030_ENCODE",
        "u16",
        &first_pointers(&points(d, "gb18030")?, |_| true),
    );
    pairs(
        &mut out,
        "`index pointer` over `index EUC-KR`, by code point.",
        "EUC_KR_ENCODE",
        "u16",
        &first_pointers(&points(d, "euc-kr")?, |_| true),
    );
    pairs(
        &mut out,
        "`index pointer` over `index jis0208`, by code point. EUC-JP's \
         encoder uses this one.",
        "JIS0208_ENCODE",
        "u16",
        &first_pointers(&points(d, "jis0208")?, |_| true),
    );
    // "The index Shift_JIS pointer ... is index jis0208 excluding all
    // entries whose pointer is in the range 8272 to 8835, inclusive."
    pairs(
        &mut out,
        "`index Shift_JIS pointer`: `index jis0208` with pointers 8272 to \
         8835 excluded, so the later of each duplicated code point is \
         used (Section 5).",
        "SHIFT_JIS_ENCODE",
        "u16",
        &first_pointers(&points(d, "jis0208")?, |p| !(8272..=8835).contains(&p)),
    );
    // "The index Big5 pointer ... is index Big5 excluding all entries
    // whose pointer is less than (0xA1 - 0x81) x 157 ... If codePoint
    // is U+2550, U+255E, U+2561, U+256A, U+5341, or U+5345, then return
    // the last pointer corresponding to codePoint."
    let big5_floor = (0xA1_usize - 0x81) * 157;
    let last_wins: [u32; 6] = [0x2550, 0x255E, 0x2561, 0x256A, 0x5341, 0x5345];
    let mut big5_encode: BTreeMap<u32, u32> = BTreeMap::new();
    for (p, cp) in big5.iter().enumerate() {
        let (Some(cp), true) = (cp, p >= big5_floor) else {
            continue;
        };
        let Ok(pp) = u32::try_from(p) else { continue };
        if last_wins.contains(cp) {
            big5_encode.insert(*cp, pp);
        } else {
            big5_encode.entry(*cp).or_insert(pp);
        }
    }
    let big5_encode: Vec<(u32, u32)> = big5_encode.into_iter().collect();
    let _ = writeln!(
        out,
        "/// `index Big5 pointer`: `index Big5` with the pointers below\n\
         /// (0xA1 − 0x81) × 157 excluded, so a Hong Kong Supplementary\n\
         /// Character Set extension is never returned literally. For\n\
         /// U+2550, U+255E, U+2561, U+256A, U+5341 and U+5345 the *last*\n\
         /// pointer is used; for every other duplicate the first\n\
         /// (Section 5).\n\
         #[rustfmt::skip]\n\
         pub static BIG5_ENCODE: [(u32, u16); {}] = [",
        big5_encode.len()
    );
    let cells: Vec<String> = big5_encode
        .iter()
        .map(|(a, b)| format!("({a:#X}, {b})"))
        .collect();
    for row in cells.chunks(8) {
        let _ = writeln!(out, "    {}", row.join(", ") + ",");
    }
    out.push_str("];\n");
    Ok(out)
}

/// Every encoding's name and labels, as a table for review.
#[must_use]
pub fn table(d: &Data) -> String {
    let mut out = String::new();
    out.push_str(
        "# @generated by hg-encoding-build. Do not edit.\n\
         # Every encoding the Encoding Standard defines, its group, and\n\
         # every label that selects it.\n\
         name\tgroup\tlabels\n",
    );
    for e in &d.encodings {
        let _ = writeln!(out, "{}\t{}\t{}", e.name, e.group, e.labels.join(" "));
    }
    out
}

/// The encodings, for a caller that wants them without the files.
#[must_use]
pub fn names(d: &Data) -> Vec<&Encoding> {
    d.encodings.iter().collect()
}
