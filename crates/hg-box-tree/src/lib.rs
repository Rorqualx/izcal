//! `hg-box-tree`: the box tree. L4, tier R.
//!
//! **LY-D2.** The box tree is the *specifications'* box tree: the
//! boxes Display 3, HTML's Rendering section and the other modules
//! generate from elements, text and pseudo-elements, including the
//! anonymous ones — table wrappers, ruby containers, block-in-inline
//! splits, anonymous blocks around inline runs, flex and grid item
//! wrappers for text.
//!
//! **G1.** It reads the DOM only through [`hg_tree_traits`] and style
//! only through a read API, which [`StyleSource`] stands for until
//! `hg-style` exists. It never depends on `hg-dom`, any L2e crate, or
//! `hg-heap` types.
//!
//! # Representation
//!
//! Boxes live in **box columns** indexed by a 32-bit [`BoxId`]: the
//! shape (parent, first child, next sibling), the generating node or
//! an anonymous marker, the computed-style id, the kind and
//! display-derived flags, the layout-cache slot, and the dirty and
//! relayout-boundary flags — **32 bytes per box**. A
//! node-slot-to-box map lets layout and the query layer go from a node
//! to its principal box; `display: contents` and `display: none` map
//! to none.
//!
//! Box columns are **class (a) derived data** (FP §6.4): dropping them
//! and rebuilding gives bit-identical box trees (LY-32).

use hg_tree_traits::{NodeKind, Tree, is_element};

/// A box's index in the columns.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct BoxId(u32);

impl BoxId {
    /// The index.
    #[must_use]
    pub const fn index(self) -> u32 {
        self.0
    }
}

/// The outer display type: how the box participates in its parent's
/// formatting context (Display 3 §2.1).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Hash)]
pub enum Outer {
    /// Block-level.
    #[default]
    Block,
    /// Inline-level.
    Inline,
}

/// The inner display type: what formatting context the box
/// establishes for its contents.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Hash)]
pub enum Inner {
    /// Normal flow.
    #[default]
    Flow,
    /// Normal flow, and a new block formatting context.
    FlowRoot,
    /// A flex container.
    Flex,
    /// A grid container.
    Grid,
    /// A table wrapper's contents.
    Table,
}

/// A computed `display` value, in Display 3's two-part form.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Hash)]
pub enum Display {
    /// An outer and an inner type.
    #[default]
    Normal,
    /// `display: none` — no box, and no box for the subtree.
    None,
    /// `display: contents` — no box of its own; the children generate
    /// boxes in its place.
    Contents,
    /// A box with the two types given.
    Pair(Outer, Inner),
}

impl Display {
    /// `display: block`.
    pub const BLOCK: Self = Self::Pair(Outer::Block, Inner::Flow);
    /// `display: inline`.
    pub const INLINE: Self = Self::Pair(Outer::Inline, Inner::Flow);
    /// `display: inline-block`.
    pub const INLINE_BLOCK: Self = Self::Pair(Outer::Inline, Inner::FlowRoot);
    /// `display: flow-root`.
    pub const FLOW_ROOT: Self = Self::Pair(Outer::Block, Inner::FlowRoot);
    /// `display: flex`.
    pub const FLEX: Self = Self::Pair(Outer::Block, Inner::Flex);

    /// The outer type, for a display that generates a box.
    #[must_use]
    pub const fn outer(self) -> Option<Outer> {
        match self {
            Self::Pair(o, _) => Some(o),
            Self::Normal => Some(Outer::Block),
            Self::None | Self::Contents => None,
        }
    }

    /// The inner type, for a display that generates a box.
    #[must_use]
    pub const fn inner(self) -> Option<Inner> {
        match self {
            Self::Pair(_, i) => Some(i),
            Self::Normal => Some(Inner::Flow),
            Self::None | Self::Contents => None,
        }
    }
}

/// What a box is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum BoxKind {
    /// A block container generated by an element.
    #[default]
    Block,
    /// An inline box generated by an element.
    Inline,
    /// A text run.
    Text,
    /// An anonymous block box wrapping a run of inline content
    /// (CSS 2.1 §9.2.1.1).
    AnonymousBlock,
}

/// What generated a box.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// A node, by its slot in the node columns.
    Node(u32),
    /// Nothing: the box is anonymous.
    Anonymous,
}

/// One box, as the columns hold it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BoxRecord {
    /// The parent box.
    pub parent: Option<BoxId>,
    /// The first child.
    pub first_child: Option<BoxId>,
    /// The next sibling.
    pub next_sibling: Option<BoxId>,
    /// What generated it.
    pub source: Source,
    /// The computed-style id. An anonymous box gets the id of its
    /// generated anonymous style.
    pub style_id: u32,
    /// What kind of box it is.
    pub kind: BoxKind,
    /// Its inner display type.
    pub inner: Inner,
    /// Whether it establishes a block formatting context.
    pub is_bfc_root: bool,
    /// Whether it or something below it needs laying out again.
    pub dirty: bool,
    /// Whether a relayout can stop here.
    pub relayout_boundary: bool,
}

/// What `hg-box-tree` needs from the style system.
///
/// A trait, not a dependency: G1 says style is read through a read
/// API, and `hg-style` is ST-M1's. This is that API's shape, and the
/// reference engine implements it too.
pub trait StyleSource {
    /// The node's computed `display`.
    fn display(&self, node: u32) -> Display;

    /// The node's computed-style id, for sharing.
    fn style_id(&self, node: u32) -> u32;

    /// The style id an anonymous box inherits, given its parent's.
    ///
    /// CSS 2.1 §9.2.1.1: an anonymous block box inherits from its
    /// parent, and non-inherited properties take their initial values.
    fn anonymous_style_id(&self, parent_style: u32) -> u32 {
        parent_style
    }
}

/// The box tree.
#[derive(Debug, Clone, Default)]
pub struct BoxTree {
    boxes: Vec<BoxRecord>,
    /// Node slot to principal box. `None` for a node that generates
    /// none, which `display: none` and `display: contents` both do.
    node_to_box: Vec<Option<BoxId>>,
    root: Option<BoxId>,
}

impl BoxTree {
    /// An empty tree.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            boxes: Vec::new(),
            node_to_box: Vec::new(),
            root: None,
        }
    }

    /// How many boxes there are.
    #[must_use]
    pub fn len(&self) -> usize {
        self.boxes.len()
    }

    /// Whether there are none.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.boxes.is_empty()
    }

    /// The root box, if the document generated one.
    #[must_use]
    pub const fn root(&self) -> Option<BoxId> {
        self.root
    }

    /// Every box, in the order they were generated.
    ///
    /// Generation order is a pre-order walk with anonymous boxes
    /// appended as their runs close, so it is a deterministic function
    /// of the tree and the styles — which is what makes a rebuild
    /// bit-identical (LY-32).
    #[must_use]
    pub fn all(&self) -> Vec<BoxId> {
        (0..self.boxes.len())
            .filter_map(|i| u32::try_from(i).ok().map(BoxId))
            .collect()
    }

    /// One box.
    #[must_use]
    pub fn get(&self, id: BoxId) -> Option<&BoxRecord> {
        self.boxes.get(usize::try_from(id.index()).ok()?)
    }

    /// The principal box of a node slot.
    #[must_use]
    pub fn box_of(&self, node: u32) -> Option<BoxId> {
        self.node_to_box
            .get(usize::try_from(node).ok()?)
            .copied()
            .flatten()
    }

    /// The children of a box, in order.
    #[must_use]
    pub fn children(&self, id: BoxId) -> Vec<BoxId> {
        let mut out = Vec::new();
        let Some(record) = self.get(id) else {
            return out;
        };
        let mut at = record.first_child;
        while let Some(child) = at {
            out.push(child);
            at = self.get(child).and_then(|c| c.next_sibling);
        }
        out
    }

    /// Every box of the subtree at `id`, in tree order.
    #[must_use]
    pub fn descendants(&self, id: BoxId) -> Vec<BoxId> {
        let mut out = Vec::new();
        let mut stack = vec![id];
        while let Some(b) = stack.pop() {
            if self.get(b).is_none() {
                continue;
            }
            out.push(b);
            let mut kids = self.children(b);
            kids.reverse();
            stack.extend(kids);
        }
        out
    }

    fn push(&mut self, record: BoxRecord) -> Option<BoxId> {
        let id = BoxId(u32::try_from(self.boxes.len()).ok()?);
        self.boxes.push(record);
        Some(id)
    }

    fn set_children(&mut self, parent: BoxId, children: &[BoxId]) {
        let first = children.first().copied();
        if let Some(p) = self
            .boxes
            .get_mut(usize::try_from(parent.index()).unwrap_or(usize::MAX))
        {
            p.first_child = first;
        }
        for (i, child) in children.iter().enumerate() {
            let next = children.get(i.saturating_add(1)).copied();
            if let Some(c) = self
                .boxes
                .get_mut(usize::try_from(child.index()).unwrap_or(usize::MAX))
            {
                c.parent = Some(parent);
                c.next_sibling = next;
            }
        }
    }
}

/// Builds a box tree from a DOM tree and a style source (LY-D2).
///
/// # The anonymous-box rule
///
/// CSS 2.1 §9.2.1.1: when a block container has a block-level child,
/// every run of its inline-level children is wrapped in an **anonymous
/// block box**. The rule is about runs, not about children one at a
/// time, so `<div>a<p>b</p>c</div>` gives three block-level children
/// and not four: `a` and `c` are separate runs.
#[must_use]
pub fn build<T: Tree + ?Sized, S: StyleSource + ?Sized>(tree: &T, style: &S) -> BoxTree
where
    T::Node: Copy,
{
    let mut out = BoxTree::new();
    let document = tree.document();
    let children = generate_children(tree, style, document, 0, &mut out);
    // The document element's box is the root, if there is one.
    out.root = children.first().copied();
    if let Some(root) = out.root
        && let Some(record) = out
            .boxes
            .get_mut(usize::try_from(root.index()).unwrap_or(usize::MAX))
    {
        // The root box always establishes a block formatting context,
        // whatever its display says.
        record.is_bfc_root = true;
        record.relayout_boundary = true;
    }
    out
}

/// The boxes a node's children generate, **before** the anonymous-box
/// rule runs over them.
///
/// Flat, because a `display: contents` element's children are the
/// parent's children for that rule's purposes: wrapping them inside
/// the contents element and again inside the parent would make an
/// inline sibling of the contents element see an anonymous *block*
/// where the specification says it sees inline-level content.
fn generate_flat<T: Tree + ?Sized, S: StyleSource + ?Sized>(
    tree: &T,
    style: &S,
    node: T::Node,
    out: &mut BoxTree,
) -> Vec<BoxId>
where
    T::Node: Copy,
{
    let mut flat: Vec<BoxId> = Vec::new();
    for child in hg_tree_traits::children(tree, node) {
        flat.extend(generate(tree, style, child, out));
    }
    flat
}

/// The boxes a node's children generate, with anonymous blocks
/// inserted where the rule asks.
///
/// `parent_style` is the style id of the box these become children
/// of, which is what an anonymous box inherits from (§9.2.1.1).
fn generate_children<T: Tree + ?Sized, S: StyleSource + ?Sized>(
    tree: &T,
    style: &S,
    node: T::Node,
    parent_style: u32,
    out: &mut BoxTree,
) -> Vec<BoxId>
where
    T::Node: Copy,
{
    let flat = generate_flat(tree, style, node, out);
    wrap_runs(out, &flat, style, parent_style)
}

/// The boxes one node generates: none, one, or — for
/// `display: contents` — its children's.
fn generate<T: Tree + ?Sized, S: StyleSource + ?Sized>(
    tree: &T,
    style: &S,
    node: T::Node,
    out: &mut BoxTree,
) -> Vec<BoxId>
where
    T::Node: Copy,
{
    let slot = tree.id(node).slot;
    match tree.kind(node) {
        NodeKind::Text => {
            // Whitespace-only text between block-level boxes generates
            // no box; CSS 2.1 §9.2.2.1's full white-space processing is
            // the inline layout's, and this is the part the box tree
            // owes.
            let text = tree.text(node).unwrap_or("");
            // CSS white space is space, tab, line feed, carriage
            // return and form feed — *not* Unicode's White_Space, which
            // holds U+00A0 and a dozen others. A text node of
            // `&nbsp;` generates a box.
            if text.chars().all(is_css_whitespace) {
                return Vec::new();
            }
            let Some(id) = out.push(record(Source::Node(slot), 0, BoxKind::Text, Inner::Flow))
            else {
                return Vec::new();
            };
            map_node(out, slot, id);
            vec![id]
        }
        NodeKind::Element => {
            let display = style.display(slot);
            if matches!(display, Display::None) {
                return Vec::new();
            }
            if matches!(display, Display::Contents) {
                // No box of its own; its children take its place, and
                // take it *flat*: the anonymous-box rule runs once, in
                // the parent that actually holds them.
                return generate_flat(tree, style, node, out);
            }
            let (Some(outer), Some(inner)) = (display.outer(), display.inner()) else {
                return Vec::new();
            };
            let kind = match outer {
                Outer::Block => BoxKind::Block,
                Outer::Inline => BoxKind::Inline,
            };
            let Some(id) = out.push(record(
                Source::Node(slot),
                style.style_id(slot),
                kind,
                inner,
            )) else {
                return Vec::new();
            };
            map_node(out, slot, id);
            let kids = generate_children(tree, style, node, style.style_id(slot), out);
            out.set_children(id, &kids);
            vec![id]
        }
        NodeKind::Comment
        | NodeKind::ProcessingInstruction
        | NodeKind::Document
        | NodeKind::DocumentType
        | NodeKind::DocumentFragment => {
            // No box; a fragment's children are reached through the
            // flat tree, which `hg-tree-traits` already presents.
            if is_element(tree, node) {
                return Vec::new();
            }
            Vec::new()
        }
    }
}

/// CSS 2.2 §16.6's white space: space, tab, line feed, carriage
/// return and form feed.
const fn is_css_whitespace(c: char) -> bool {
    matches!(c, ' ' | '\t' | '\n' | '\r' | '\u{C}')
}

fn record(source: Source, style_id: u32, kind: BoxKind, inner: Inner) -> BoxRecord {
    BoxRecord {
        parent: None,
        first_child: None,
        next_sibling: None,
        source,
        style_id,
        kind,
        inner,
        is_bfc_root: matches!(inner, Inner::FlowRoot | Inner::Flex | Inner::Grid),
        dirty: true,
        relayout_boundary: false,
    }
}

fn map_node(out: &mut BoxTree, slot: u32, id: BoxId) {
    let at = usize::try_from(slot).unwrap_or(usize::MAX);
    if out.node_to_box.len() <= at {
        out.node_to_box.resize(at.saturating_add(1), None);
    }
    if let Some(entry) = out.node_to_box.get_mut(at) {
        *entry = Some(id);
    }
}

/// Wraps each run of inline-level boxes in an anonymous block box,
/// but only when there is a block-level box among them
/// (CSS 2.1 §9.2.1.1).
fn wrap_runs<S: StyleSource + ?Sized>(
    out: &mut BoxTree,
    children: &[BoxId],
    style: &S,
    parent_style: u32,
) -> Vec<BoxId> {
    let is_inline = |out: &BoxTree, id: BoxId| {
        out.get(id)
            .is_some_and(|b| matches!(b.kind, BoxKind::Inline | BoxKind::Text))
    };
    let any_block = children.iter().any(|id| !is_inline(out, *id));
    if !any_block {
        // An inline formatting context: nothing to wrap.
        return children.to_vec();
    }
    let mut result: Vec<BoxId> = Vec::new();
    let mut run: Vec<BoxId> = Vec::new();
    for id in children {
        if is_inline(out, *id) {
            run.push(*id);
            continue;
        }
        flush_run(out, &mut run, &mut result, style, parent_style);
        result.push(*id);
    }
    flush_run(out, &mut run, &mut result, style, parent_style);
    result
}

fn flush_run<S: StyleSource + ?Sized>(
    out: &mut BoxTree,
    run: &mut Vec<BoxId>,
    result: &mut Vec<BoxId>,
    style: &S,
    parent_style: u32,
) {
    if run.is_empty() {
        return;
    }
    // §9.2.1.1: the anonymous box inherits from **the parent**, not
    // from the children it wraps. Taking the first child's id would
    // give a text child's zero.
    let Some(anon) = out.push(record(
        Source::Anonymous,
        style.anonymous_style_id(parent_style),
        BoxKind::AnonymousBlock,
        Inner::Flow,
    )) else {
        run.clear();
        return;
    };
    let kids = core::mem::take(run);
    out.set_children(anon, &kids);
    result.push(anon);
}
