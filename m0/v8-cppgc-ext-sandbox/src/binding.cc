// The inline v8::V8::Initialize() computes a build-configuration bitmask from
// *this* translation unit's defines (pointer compression, 31-bit Smis,
// sandbox, V8_ENABLE_CHECKS, Android) and V8 FATALs with "Embedder-vs-V8
// build configuration mismatch" if it differs from the library's. Only call
// this from a process that has not initialized V8 through rusty_v8.
bool v8_cppgc_ext__V8__Initialize_with_shim_build_config() {
  return v8::V8::Initialize();
}

int v8_cppgc_ext__shim_build_configuration() {
  int c = 0;
  if (v8::internal::PointerCompressionIsEnabled()) c |= 1 << 0;
  if (v8::internal::SmiValuesAre31Bits()) c |= 1 << 1;
  if (v8::internal::SandboxIsEnabled()) c |= 1 << 2;
#ifdef V8_ENABLE_CHECKS
  c |= 1 << 3;
#endif
#ifdef CPPGC_CAGED_HEAP
  c |= 1 << 8;
#endif
#ifdef CPPGC_POINTER_COMPRESSION
  c |= 1 << 9;
#endif
#ifdef CPPGC_YOUNG_GENERATION
  c |= 1 << 10;
#endif
#ifdef CPPGC_ENABLE_LARGER_CAGE
  c |= 1 << 11;
#endif
#ifdef CPPGC_SLIM_WRITE_BARRIER
  c |= 1 << 12;
#endif
#ifdef CPPGC_ENABLE_API_CHECKS
  c |= 1 << 13;
#endif
#ifdef CPPGC_SUPPORTS_OBJECT_NAMES
  c |= 1 << 14;
#endif
#ifdef CPPGC_ENABLE_OBJECT_SECTION_GCINFO
  c |= 1 << 15;
#endif
  return c;
}

// Link-time probes: the define-gated slow paths are private, but the
// header-inline code compiled into this file references them (verified with
// `nm -u` on the shim object, see README):
//   CPPGC_SLIM_WRITE_BARRIER + CPPGC_POINTER_COMPRESSION
//       -> WriteBarrier::CombinedWriteBarrierSlow<kCompressed>  (Member::operator=)
//   CPPGC_YOUNG_GENERATION -> WriteBarrier::GenerationalBarrierSlow
//       (HeapConsistency::GenerationalBarrier below)
//   CPPGC_CAGED_HEAP -> CagedHeapBase::g_heap_base_ (GetWriteBarrierType)
//   CPPGC_POINTER_COMPRESSION -> CageBaseGlobal::g_base_ (Member storage)
// librusty_v8.a only defines these when it was built with the same defines,
// so a define we claim but the prebuilt lacks fails to link.
void v8_cppgc_ext__Member__assign_with_shim(void* slot, RustObj* obj) {
  *static_cast<cppgc::Member<RustObj>*>(slot) = obj;
}

// Member compression cross-check: the *shim* compresses `obj` into `slot`
// using the header-inline code compiled here; the Rust test then reads it back
// with rusty_v8's prebuilt `cppgc__Member__Get` (and vice versa).
void v8_cppgc_ext__Member__construct_with_shim(void* slot, RustObj* obj) {
  ::new (slot) cppgc::Member<RustObj>(obj);
}
RustObj* v8_cppgc_ext__Member__get_with_shim(const void* slot) {
  return static_cast<const cppgc::Member<RustObj>*>(slot)->Get();
}
void v8_cppgc_ext__Member__destruct_with_shim(void* slot) {
  std::destroy_at(static_cast<cppgc::Member<RustObj>*>(slot));
}
size_t v8_cppgc_ext__sizeof_Member() { return sizeof(cppgc::Member<RustObj>); }

