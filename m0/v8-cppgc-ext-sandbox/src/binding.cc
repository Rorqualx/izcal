void cppgc__HeapStatistics__GetTotals(const cppgc::HeapStatistics* self,
                                      cppgc__HeapStatistics__Totals* out) {
  out->committed_size_bytes = self->committed_size_bytes;
  out->resident_size_bytes = self->resident_size_bytes;
  out->used_size_bytes = self->used_size_bytes;
  out->pooled_memory_size_bytes = self->pooled_memory_size_bytes;
  out->space_count = self->space_stats.size();
  out->type_name_count = self->type_names.size();
  out->detail_level = static_cast<uint8_t>(self->detail_level);
}

bool cppgc__HeapStatistics__GetSpace(const cppgc::HeapStatistics* self,
                                     size_t space_index,
                                     cppgc__HeapStatistics__Space* out) {
  if (space_index >= self->space_stats.size()) return false;
  const auto& s = self->space_stats[space_index];
  out->name = s.name.data();
  out->name_len = s.name.size();
  out->committed_size_bytes = s.committed_size_bytes;
  out->resident_size_bytes = s.resident_size_bytes;
  out->used_size_bytes = s.used_size_bytes;
  out->page_count = s.page_stats.size();
  return true;
}

bool cppgc__HeapStatistics__GetPage(const cppgc::HeapStatistics* self,
                                    size_t space_index, size_t page_index,
                                    cppgc__HeapStatistics__Page* out) {
  if (space_index >= self->space_stats.size()) return false;
  const auto& s = self->space_stats[space_index];
  if (page_index >= s.page_stats.size()) return false;
  const auto& p = s.page_stats[page_index];
  out->committed_size_bytes = p.committed_size_bytes;
  out->resident_size_bytes = p.resident_size_bytes;
  out->used_size_bytes = p.used_size_bytes;
  out->object_statistics = p.object_statistics.data();
  out->object_statistics_len = p.object_statistics.size();
  return true;
}

bool cppgc__HeapStatistics__GetFreeList(const cppgc::HeapStatistics* self,
                                        size_t space_index,
                                        cppgc__HeapStatistics__FreeList* out) {
  if (space_index >= self->space_stats.size()) return false;
  const auto& f = self->space_stats[space_index].free_list_stats;
  out->bucket_size = f.bucket_size.data();
  out->bucket_size_len = f.bucket_size.size();
  out->free_count = f.free_count.data();
  out->free_count_len = f.free_count.size();
  out->free_size = f.free_size.data();
  out->free_size_len = f.free_size.size();
  return true;
}

