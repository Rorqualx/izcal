// --- cppgc::subtle::HeapConsistency -------------------------------------------
// WriteBarrierParams is an internal struct whose layout depends on build
// flags, so it never leaves C++: each entry point computes the barrier type
// and dispatches in one call, the same way Member::operator= does.

uint8_t cppgc__HeapConsistency__GetWriteBarrierType(const void* slot,
                                                    const void* value) {
  cppgc::subtle::HeapConsistency::WriteBarrierParams params;
  return static_cast<uint8_t>(
      cppgc::subtle::HeapConsistency::GetWriteBarrierType(slot, value,
                                                          params));
}

// Barrier for "`value` was just written into `slot`" (Dijkstra-style marking
// barrier, or the generational barrier when young generation is enabled).
void cppgc__HeapConsistency__WriteBarrier(const void* slot,
                                          const void* value) {
  using HC = cppgc::subtle::HeapConsistency;
  HC::WriteBarrierParams params;
  switch (HC::GetWriteBarrierType(slot, value, params)) {
    case HC::WriteBarrierType::kMarking:
      HC::DijkstraWriteBarrier(params, value);
      break;
    case HC::WriteBarrierType::kGenerational:
      HC::GenerationalBarrier(params, slot);
      break;
    case HC::WriteBarrierType::kNone:
      break;
  }
}

// Marking barrier only; returns whether it fired.
bool cppgc__HeapConsistency__DijkstraWriteBarrier(const void* slot,
                                                  const void* value) {
  using HC = cppgc::subtle::HeapConsistency;
  HC::WriteBarrierParams params;
  if (HC::GetWriteBarrierType(slot, value, params) ==
      HC::WriteBarrierType::kMarking) {
    HC::DijkstraWriteBarrier(params, value);
    return true;
  }
  return false;
}

// Re-trace an already-marked `object` (Steele-style); returns whether it fired.
bool cppgc__HeapConsistency__SteeleWriteBarrier(const void* object) {
  using HC = cppgc::subtle::HeapConsistency;
  HC::WriteBarrierParams params;
  if (HC::GetWriteBarrierType(object, params) ==
      HC::WriteBarrierType::kMarking) {
    HC::SteeleWriteBarrier(params, object);
    return true;
  }
  return false;
}

// Generational barrier only; returns whether it fired.
bool cppgc__HeapConsistency__GenerationalBarrier(const void* slot,
                                                 const void* value) {
  using HC = cppgc::subtle::HeapConsistency;
  HC::WriteBarrierParams params;
  if (HC::GetWriteBarrierType(slot, value, params) ==
      HC::WriteBarrierType::kGenerational) {
    HC::GenerationalBarrier(params, slot);
    return true;
  }
  return false;
}

